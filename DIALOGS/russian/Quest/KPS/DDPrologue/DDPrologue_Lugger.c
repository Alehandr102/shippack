// Gregg: Томми Толстяк и его команда - альтернативный пролог «Необитаемый остров»
// (перенос из К:ПС). Общий файл на троих: Томми (узлы 1-6), Вальтер Кортен (7-13)
// и Джонни Нортон (14).
// Логика - Program\Quests\reaction_functions\ddprologue.c

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Все вопросы к капитану.";
			link.l1 = "Хорошо.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "Здорово! Я капитан Томми Толстяк. Что тебе надо?";
			link.l1 = "Капитан " + GetFullName(PChar) + ". Слушай, Томми, у меня к тебе дело, и ты мне можешь помочь в нём.";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "И что за дело?";
			link.l1 = "Мы хотим доплыть до ближайшего английского или французского порта.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Я готов доставить вас на Мартинику. Пойдёт?";
			link.l1 = "Отлично, нас это устраивает.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Сколько? Назовите сумму.";
			link.l1 = "Полторы тысячи вы получите авансом и ещё полторы тысячи по прибытии на Мартинику.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "По рукам! Давайте сюда аванс.";
			link.l1 = "Вот, полторы тысячи, как и договаривались. Когда мы можем подняться на борт?";
			link.l1.go = "6";
		break;

		// Gregg: деньги снимаются здесь, и это верно - игрок уже отдал их репликой узла 5
		case "6":
			AddMoneyToCharacter(PChar, -1500);
			dialog.text = "...(смеётся)... Вот что, капитан Неудачни" + GetSexPhrase("к", "ца") + ", на борт ты поднимешься ещё не скоро, если вообще поднимешься, а не сдохнешь на этом острове. Ха! А ты думал" + GetSexPhrase("", "а") + ", я повезу тебя на Мартинику, наивн" + GetSexPhrase("ый", "ая") + "? Проваливай, если жизнь дорога, я пока добрый.";
			link.l1 = "Вздумал обвести меня вокруг пальца, Толстяк? Ну уж нет, я больше никому не позволю себя одурачить. Защищайся!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartGameLuggerCapBattle");
		break;

		case "7":
			dialog.text = "Теперь вы наш капитан, мистер " + GetHeroLastName() + ".";
			link.l1 = "Сожалею, что пришлось убить вашего капитана, но он обманул меня, за что и поплатился своей жизнью.";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Мы видели, что случилось, капитан " + GetHeroLastName() + ", и полностью на вашей стороне. Признаться, мы благодарны вам за убийство этого бесполезного мешка. Мы давно уже хотели устроить мятеж и переизбрать капитана.";
			link.l1 = "...(улыбается)... Выходит, я появил" + GetSexPhrase("ся", "ась") + " как нельзя кстати.";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Есть немного, капитан. Правда, корабль наш в плачевном состоянии. Этот идиот пошёл против галеона.";
			link.l1 = "На люггере против галеона? У него с головой всё в порядке?";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Вот и я о том же. Первый же бортовой залп галеона отрезвил его ум, мы развернули корабль и бежали с поля боя. Нам повезло, что удалось уйти от погони.";
			link.l1 = "А зачем вы бросили якорь близ этого острова? Пополнить запасы?";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Здесь мы хотели порешить этого ублюдка. Если бы вы пришли на пять минут позже, мы бы сами прикончили Толстяка.";
			link.l1 = "Понятно. Ладно, на разговоры нет времени, пора сниматься с якоря и убираться отсюда.";
			link.l1.go = "13";
		break;

		case "13":
			dialog.text = "Капитан, у нас в трюме небольшой груз какао, который мы везём на Барбадос человеку по имени Ричард Тилльман. Я думаю, вы примете на себя обязательство старого капитана доставить груз?";
			link.l1 = "Безусловно. Курс на Барбадос.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartGameHappyEnd");
		break;

		case "14":
			dialog.text = "Слушаю вас, капитан?";
			link.l1 = "Вольно.";
			link.l1.go = "exit";
			NextDiag.TempNode = "14";
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
