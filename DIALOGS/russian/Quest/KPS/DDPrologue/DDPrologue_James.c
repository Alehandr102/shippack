// Gregg: Джеймс Робинсон - альтернативный пролог «Необитаемый остров» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\ddprologue.c

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			if (CheckAttribute(PChar, "StartDamnedDestiny"))
			{
				if (PChar.StartDamnedDestiny == "1")
				{
					dialog.text = "Капитан, нужно поторопиться в грот!";
					link.l1 = "Ты прав, пойдём.";
					link.l1.go = "exit";
					break;
				}
			}
			dialog.text = "Что вам надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "Start_1":
			dialog.text = "Капитан " + GetHeroLastName() + ", вы живы! Чёрт возьми, как же я рад видеть вас! Не ранены?";
			link.l1 = "Нет, кажется. Только голова очень сильно болит.";
			link.l1.go = "Start_2";
		break;

		case "Start_2":
			dialog.text = "Неудивительно. Вы сильно ударились о пушку при том страшном взрыве. Вам вообще сильно повезло, что вы выжили.";
			link.l1 = "А что вообще произошло? Я совсем ничего не помню...";
			link.l1.go = "Start_3";
		break;

		case "Start_3":
			dialog.text = "Вообще ничего не помните?";
			link.l1 = "...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartDamnedDestinyStartFade");
		break;

		case "Start_4":
			dialog.text = "Даже как меня зовут?";
			link.l1 = "Нет, ничего не могу вспомнить.";
			link.l1.go = "Start_5";
		break;

		case "Start_5":
			dialog.text = "Видимо, крепко вы приложились о ту пушку. Ладно, капитан, слушайте. Я Джеймс Робинсон, поступил к вам на службу около трёх месяцев тому назад. Я был горд, что мне выпала честь плавать на корабле капитана " + GetMainCharacterNameGen() + ". \n Где-то с месяц назад в таверне на Бермудах вы встретились с вашим старым другом, капитаном Грифо Сайфусом, который предложил вам одно дело. Атаку небольшого судна, на котором якобы находилась партия алмазов из Африки. Вы договорились встретиться здесь, на необитаемом острове Доминика, согласовать план и действовать, но \n Грифо предал вас. И всех нас тоже.";
			link.l1 = "Предал? Как это случилось?";
			link.l1.go = "Start_6";
		break;

		case "Start_6":
			dialog.text = "Ночью, когда корабли сблизились, он разрядил в нашу быстроходную шебеку все пушки левого борта, после чего развернулся и полил нашу палубу картечью уже с правого. Уже во время первого залпа половина нашей команды погибла, а вы крепко ударились головой о пушку и потеряли сознание. \n Мы хотели было дать отпор, но после второго залпа, который унёс жизни ещё пятнадцати-двадцати человек, поняли, что это бесполезно, и спрыгнули в море. Я видел, как наш боцман Энди Рэйдол взвалил вас на плечо и выпрыгнул вместе с вами. Мне удалось добраться до берега, где я и встретил вас. Чёрт побери, кэп, как же я рад, что вы живы!";
			link.l1 = "Я тоже рад" + GetSexPhrase("", "а") + ", " + NPChar.name + ". Как думаешь, сколько человек из нашей команды выжили?";
			link.l1.go = "Start_7";
		break;

		case "Start_7":
			dialog.text = "Не знаю, кэп. Не думаю, что многим из тех, кто спрыгнул в море, удалось спастись. С корабля Грифо Сайфуса ещё долго шмаляли картечью по воде, в надежде перебить всех нас. Так что сами понимаете, кэп, если и есть выжившие, то их от силы человека четыре будет, ну пять, не больше.";
			link.l1 = "Слушай, " + NPChar.name + ", я тут подумал" + GetSexPhrase("", "а") + ", что зря мы здесь на берегу стоим. Если корабль Сайфуса ещё здесь, нас заметят и обстреляют. Или, чего хуже, вышлют десант на охоту за выжившими. Надо двигать в джунгли.";
			link.l1.go = "Start_8";
		break;

		case "Start_8":
			dialog.text = "Я знаю, где-то здесь неподалёку есть небольшой грот, там мы сможем укрыться на время и подумать, что делать дальше. И кто знает, может, те, кто выжил, нашли своё прибежище там.";
			link.l1 = "Тогда нечего медлить, вперёд!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartGameGoToGrot");
		break;

		case "Start_9":
			dialog.text = "Капитан " + GetHeroLastName() + ", отличная новость! Небольшой люггер бросил якорь близ соседнего пляжа! Капитан и несколько его помощников уже высадились на побережье, и если вы поспешите, то мы ещё сможем застать их там.";
			link.l1 = "Превосходно, " + NPChar.name + ". Выдвигаемся!";
			link.l1.go = "Start_10";
		break;

		case "Start_10":
			dialog.text = "Подождите, капитан " + GetHeroLastName() + "! Будьте осторожны в переговорах с кэпом люггера, мне он показался подозрительным.";
			link.l1 = "Тогда ты, Джеймс, и ты, Энди, прикройте меня, если что-то пойдёт не так. Всё понятно? Тогда вперёд!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartGameNextDayToLugger");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
