// Gregg: Пьер Арну и Рене Матеж, люди Сайфуса в гроте - альтернативный пролог
// «Необитаемый остров» (перенос из К:ПС). Сцена подслушанная: игрок сидит в укрытии,
// реплики обеих сторон - это разговор пиратов между собой.
// Логика - Program\Quests\reaction_functions\ddprologue.c

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Что вам надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "Пьер Арну: И чего мы сюда залезли? Нет здесь никого, и быть не может. Под таким шквалом картечи ни у кого нет шансов выжить.";
			link.l1 = "Рене Матеж: Капитан приказал прочесать каждый дюйм острова. Кончай ныть и начинай обыскивать грот.";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Пьер Арну: Ну, нет, туда дальше я не пойду, там ещё мрачнее, чем здесь, и наплевать мне на приказы капитана.";
			link.l1 = "Рене Матеж: Вот как. Ты посмеешь ослушаться капитанского приказа?";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Пьер Арну: А чего ты сам туда не идёшь, раз такой умный? Давай лезь, а я посмотрю, что с тобой сделают.";
			link.l1 = "Рене Матеж: ...(усмехается)... И кому бы это там со мной что-то делать?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Пьер Арну: Так ты не слышал?";
			link.l1 = "Рене Матеж: Не слышал о чём?";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Пьер Арну: О злобных мерзких тварях, обитающих в этих гротах, которые убивают любого, кто зайдёт на их территорию.";
			link.l1 = "Рене Матеж: ...(усмехается)... Детские сказки, чтобы пугать маленьких детишек.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Пьер Арну: ...(злобно)... Детские сказки? Ну, раз это детские сказки, тогда тебе точно нечего бояться. Давай лезь, а я за тобой.";
			link.l1 = "Рене Матеж: Гхм... Эмм... Вообще-то ты прав, здесь наверное никого нет, даже искать не надо.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Пьер Арну: Что, струсил? Боишься, прохвост.";
			link.l1 = "Рене Матеж: Не боюсь! Просто... Просто вспомнил нашу картечь, и... Под таким шквалом огня действительно никто бы не выжил. Всё, пошли.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Пьер Арну: Ты струсил, Рене, и не отпирайся, я вижу это. Ладно, давай выбираться отсюда, а то мурашки по коже от этого места.";
			link.l1 = "Рене Матеж: Стой. Капитану скажем, что прочесали этот грот вдоль и поперёк, ты понял?";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Пьер Арну: Нет, лучше ты один это скажешь, тебе он больше доверяет.";
			link.l1 = "Рене Матеж: Так и быть, скажу. Всё, пошли отсюда.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("StartGameEnemyInGrotExit");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
