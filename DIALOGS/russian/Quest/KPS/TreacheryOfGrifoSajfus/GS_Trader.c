// Gregg: торговец с африканскими алмазами - квест «Предательство Грифо Сайфуса»
// (перенос из К:ПС). Логика - Program\Quests\reaction_functions\grifosajfus.c
// Узлы 1-4 - разговор до драки, 5-15 - рассказ сбитого до сдачи торговца.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Что вам надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "Эй, не хочешь пару африканских алмазов прикупить? Алмазы высший сорт, в цене сойдёмся.";
			link.l1 = "Где ты их взял?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "А тебе какое дело?";
			link.l1 = "Где ты взял эти алмазы? Отвечай!";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Да пошёл ты!";
			link.l1 = "Не нарывайся, или пожалеешь.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Ха! Да что ты мне можешь сделать? Думаешь, ты " + GetSexPhrase("один", "одна") + " тут такой умн" + GetSexPhrase("ый", "ая") + "? Другие тоже пробовали, да на том свете уже все. Так что отвалил" + GetSexPhrase("", "а") + " бы ты быстро, пока я тебе кости не переломал.";
			link.l1 = "Ну, попробуй.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusBattleWithTrader");
		break;

		case "5":
			dialog.text = "Хорошо, хорошо, я скажу, всё скажу.";
			link.l1 = "Я слушаю.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Я англичанин, служил матросом на шхуне ''Радуга''. Несколько дней назад меня и троих моих товарищей ссадили на Теркс за попытку поднять мятеж на корабле. Через три дня на остров приплыли ловцы жемчуга." + NewStr() + "Мы представились как испанцы, потерпевшие кораблекрушение, кое-как договорились с ловцами, благо по-испански умели болтать, что они доставят нас хотя бы до Пуэрто-Рико. А на следующий день один из них обнаружил затонувшую на мелководье шебеку, метрах в семи-десяти от поверхности...";
			link.l1 = "Стой! Та шебека называлась ''Пиранья''?";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Да вроде бы так и называлась. Ловцы точно название не рассмотрели. А ты откуда знаешь?";
			link.l1 = "Ниоткуда. Продолжай.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Ловцы вытащили из капитанской каюты кучу уцелевшего добра. Среди всего этого там был маленький сундук с этими алмазами. Один из них, видимо знаток, смекнул, что алмазы из Африки, и всем рассказал.";
			link.l1 = "Вот так вот запросто определили, что они африканские?";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Я же говорю, знаток он был и в этих вещах смыслил хорошо.";
			link.l1 = "Хорошо, давай дальше, что они с ними сделали?";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Пересчитали, положили обратно в сундук и под строжайшую охрану его. С рассветом думали отплыть, но ночью напали пираты. Они, видимо, прознали, что ловцы промышляют на Терксе, и прибыли.";
			link.l1 = "И что дальше?";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Они застали ловцов врасплох. Высадили десант мушкетёров, первыми же залпами практически всех и положили. Мне и ещё нескольким ловцам удалось выжить под этим градом картечи со всех сторон, и мы отступили в джунгли." + NewStr() + "Большая часть пиратского отряда осталась на берегу, а малая устремилась за нами в погоню. Не знаю, что случилось с остальными, но мне удалось оторваться от преследования.";
			link.l1 = "А сундук с алмазами достался тем пиратам?";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Дослушай до конца. Я добежал до северного берега и увидел там корчащегося от боли раненого ловца. Он рассказал мне про тартану, спрятанную на этом каменистом берегу, и велел убираться с острова, пока корсары не добрались досюда. " + NewStr() + "Потом у него ослаб голос, и единственное, что он успел произнести, так это то, что во время погони сундук с алмазами был с ним и он спрятал его...";
			link.l1 = "Где? Куда он его запрятал?";
			link.l1.go = "13";
		break;

		case "13":
			dialog.text = "Он не успел этого сказать. Отдал богу душу.";
			link.l1 = "Значит, сундук с алмазами всё ещё где-то на Терксе?";
			link.l1.go = "14";
		break;

		case "14":
			dialog.text = "Если пираты его не нашли. Они наверняка узнали про него и прочесали весь остров вдоль и поперёк.";
			link.l1 = "Могли и не прознать. В любом случае Теркс необходимо посетить.";
			link.l1.go = "15";
		break;

		case "15":
			dialog.text = "А что со мной, кэп? Я могу идти? Я рассказал всё, что знаю.";
			link.l1 = "Чёрт с тобой, живи, но на глаза мне не попадайся.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusTraderExit");
		break;

		case "CitizenNotBlade":
			NextDiag.TempNode = "First time";
			dialog.text = "Острожней на поворотах, приятель, когда бежишь с оружием в руках. Я ведь могу и занервничать...";
			link.l1 = RandPhraseSimple("Понял" + GetSexPhrase("", "а") + ".", "Убираю.");
			link.l1.go = "exit";
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
