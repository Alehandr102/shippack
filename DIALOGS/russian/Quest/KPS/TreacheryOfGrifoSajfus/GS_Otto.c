// Gregg: Отто Гроберг - квест «Предательство Грифо Сайфуса» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\grifosajfus.c
// Узлы 1-2 - незнакомец с запиской в Пиратском городе, 3-15 - сам Отто в таверне,
// 16-19 - расчёт в Пуэрто-Принсипе.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Что вам надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "Капитан " + GetFullName(PChar) + "? Мне велели передать вам это по прибытию.";
			link.l1 = "Кто велел?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Не знаю. Может, в записке написано.";
			link.l1 = "Ладно, давай записку.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusTakeNotice");
		break;

		case "3":
			dialog.text = "А-а, капитан " + PChar.name + ", рад, что вы, наконец, прибыли на Бермуды. Меня зовут Отто Гроберг.";
			link.l1 = "Что угодно, Отто?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "У вас есть то, что должно было принадлежать мне.";
			link.l1 = "Что именно?";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Алмазы, капитан " + GetHeroLastName() + ", алмазы, которые вы нашли на Терксе. Я готов купить их у вас.";
			link.l1 = "Цена будет в несколько раз выше, чем на обычные алмазы, и потом...";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Я знаю цену этих алмазов, капитан " + GetHeroLastName() + ", и готов отдать за них самый ценный товар в мире.";
			link.l1 = "И что же это за товар?";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Снова не догадываетесь, капитан?";
			link.l1 = "Говори прямо, не тяни.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Информация, капитан " + GetHeroLastName() + ". Я куплю у вас эти алмазы за весьма интересные и крайне полезные для вас сведения.";
			link.l1 = "За дурака меня держишь, Отто? Думаешь, что я продам тебе алмазы за информацию?";
			link.l1.go = "9";
		break;

		// Gregg: без альтернативного пролога «Пиранья» ГГ никогда не принадлежала -
		// он идёт за легендой, а не за своим кораблём
		case "9":
			if (CheckAttribute(PChar, "TreacheryOfGrifoSajfus.NoPiranha"))
			{
				dialog.text = "За ценную информацию, капитан. Информацию о корабле-мечте, который намного лучше той самой ''Пираньи'', которую вы ищете.";
				link.l1 = "Лучше ''Пираньи''? Говорят, лучше неё на Карибах ничего не ходило.";
			}
			else
			{
				dialog.text = "За ценную информацию, капитан. Информацию о корабле-мечте, который намного лучше ''Пираньи'', на которой вы плавали.";
				link.l1 = "Нет, не было и не будет корабля, который был бы лучше, чем ''Пиранья''!";
			}
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Ошибаетесь, капитан. Я кое-что знаю о ''Пиранье''. На верфи, где она была создана, построили ещё два корабля. По своему внешнему виду все три корабля не отличить друг от друга. Сначала был построен ''Хамелеон'' с явными недостатками в конструкции, потом ''Пиранья'', при создании которой были учтены все промашки и недостатки ''Хамелеона''." + NewStr() + "Но вершиной технической мысли был корабль, который воплотил в себе весь опыт, накопленный при постройке ''Хамелеона'' и ''Пираньи'' - ''Марлин''. Именно этот корабль я и предлагаю вам захватить. Соглашайтесь, капитан, этот корабль - произведение искусства. Конечно, придётся попотеть при захвате судна, но оно того стоит.";
			link.l1 = "Ну, хорошо, допустим, я продаю тебе алмазы, ты говоришь мне, где этот корабль найти, я плыву туда и ничего не нахожу.";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Это проверенная информация, капитан. Впрочем, если вам нужны гарантии, я готов вам их предоставить.";
			link.l1 = "И что это за гарантии?";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Хм. Дайте-ка подумать. Я могу отправиться вместе с вами пассажиром и опознать судно, когда мы его нагоним. В драку не полезу, но за себя постоять сумею.";
			link.l1 = "Хм. Со шпагой хорошо обращаешься?";
			link.l1.go = "13";
		break;

		case "13":
			dialog.text = "Не хуже вашего брата, корсара. Таких гарантий достаточно?";
			link.l1 = "Вполне. Итак, где мне найти этот чудо-корабль?";
			link.l1.go = "14";
		break;

		case "14":
			dialog.text = "Через неделю ''Марлин'' прибудет в Пуэрто-Принсипе. У нас в запасе дней десять, чтобы добраться до Кубы, капитан. После захвата высадите меня в порту Пуэрто-Принсипе.";
			link.l1 = "Медлить нельзя! Нужно немедленно сниматься с якоря!";
			link.l1.go = "15";
		break;

		case "15":
			TakeNItems(PChar, "SajfusDiamondChest", -1);
			dialog.text = "Эй, а мои алмазы?";
			link.l1 = "Вот твои камни, а сейчас - вперёд.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusToPuertoPrincipe");
		break;

		case "16":
			if (PChar.TreacheryOfGrifoSajfus.MarlinSink == true)
			{
				dialog.text = "Сожалею, " + PChar.name + ", ты " + GetSexPhrase("был", "была") + " близк" + GetSexPhrase("", "а") + " к победе, но...";
				link.l1 = "Да, знаю. Жаль, конечно, но ничего не поделаешь, надо жить дальше.";
				link.l1.go = "17";
			}
			else
			{
				dialog.text = "Поздравляю, " + PChar.name + ". Теперь вы капитан одного из самых быстрых судов на Карибах.";
				link.l1 = "А ты был прав, этот корабль просто великолепен! Само совершенство.";
				link.l1.go = "19";
			}
		break;

		case "17":
			dialog.text = "Сколько ещё быстроходных судов на Карибах? И одно из них ты обязательно захватишь!";
			link.l1 = "Да уж постараюсь, если выпадет ещё один шанс, я его не упущу.";
			link.l1.go = "18";
		break;

		case "18":
			dialog.text = "Вот это верно. Ладно, " + PChar.name + ", некогда мне, бежать надо. Прощай.";
			link.l1 = "Счастливо, Отто.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusOttoExit");
		break;

		case "19":
			dialog.text = "Ещё раз поздравляю! Я бы с тобой выпил, да некогда мне, бежать надо. Прощай, " + PChar.name + ", и береги корабль.";
			link.l1 = "Счастливо, Отто.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TreacheryOfGrifoSajfusOttoExit");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
