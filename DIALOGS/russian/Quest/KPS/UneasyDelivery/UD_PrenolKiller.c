// Gregg: Джон и Нильс, кредиторы Жака Преноля - квест «Товар для Ричарда Тилльманна»
// (перенос из К:ПС). Сцена подслушанная: ГГ стоит в стороне, а реплики обеих сторон -
// это разговор кредиторов с Пренолем, а потом между собой.
// Узлы 1-5 ведёт Джон, 6-10 - Нильс.
// Логика - Program\Quests\reaction_functions\uneasydelivery.c

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Что вам надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "Джон: Ну что, Преноль, долги принято отдавать. Мы дали тебе последний срок, до сегодняшней ночи, и сейчас ждём своих денег.";
			link.l1 = "Жак Преноль: Я не смог принести их сюда, Джон, я...";
			link.l1.go = "2";
		break;

		// Gregg: в К:ПС долг был «двести пятьдесят штук», четверть миллиона. Суммы квеста
		// урезаны на порядок, поэтому здесь двадцать пять тысяч: столько же лежит в схроне
		// сверх долга Шону, и цифры сходятся между собой.
		case "2":
			dialog.text = "Джон: Что?! Преноль, мы разве не предупреждали тебя, а?";
			link.l1 = "Жак Преноль: Но я же не такой дурак, чтобы привезти сюда, на Бермуды, двадцать пять тысяч. Да здесь все готовы глотки друг другу перерезать за пару сотен! А что бы они сделали со мной за две недели, пока я ждал вас, если бы узнали, что у меня с собой такие деньги?";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Джон: Значит, деньги ты нам не принёс, Преноль?";
			link.l1 = "Жак Преноль: Я спрятал их у маяка. Вот карта. Вам остаётся лишь отправиться туда и забрать их.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Джон: Жак, мы тебе говорили: не принесёшь деньги сюда - и тебе конец!";
			link.l1 = "Жак Преноль: Нет! Не убивай меня, Джон, я же объяснил, почему я их сюда не привёз.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Джон: Нас это не интересует. Мы сказали тебе, чтобы сегодня деньги были здесь. Вместо этого ты посылаешь нас к какому-то маяку. Нет, Преноль, мы слишком хорошо тебя знаем, чтобы поверить, что ты действительно спрятал там деньги.";
			link.l1 = "Жак Преноль: Нет! Нет, Джон, не убивай меня! Нет, прошу...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("UneasyDeliveryPrenolKill");
		break;

		case "6":
			dialog.text = "Джон: Вот идиот. Говорил же я ему: не привезёшь деньги - убью к чертям собачьим.";
			link.l1 = "Нильс: А может, проверим тот схрон у маяка? Кто знает, вдруг он действительно спрятал деньги там.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Джон: И ты поверил ему? Поверил тому, что он нам тут наговорил про маяк и деньги?";
			link.l1 = "Нильс: А вдруг? Что нам стоит проверить? Карта есть, время тоже.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Джон: Хм. А ты прав, чёрт возьми!";
			link.l1 = "Нильс: Тогда отплываем прямо сейчас, чего время терять.";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Джон: Эй, а это что за хмырь?";
			link.l1 = "Нильс: Ты про кого?";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Джон: Да вон стоит, глазами сверкает.";
			link.l1 = "Нильс: " + GetSexPhrase("Он нас подслушивал. Он видел", "Она нас подслушивала. Она видела") + ", как мы убили Преноля. Прикончим " + GetSexPhrase("его", "её") + ".";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("UneasyDeliveryBattleWithPrenolKillers");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
