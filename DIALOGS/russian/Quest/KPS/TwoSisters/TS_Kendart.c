// Gregg: Алехон Кендарт - «Две сестры», глава 10 сюжетной линии К:ПС.
// Логика - Program\Quests\reaction_functions\twosisters.c.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			// Кендарт ждёт трижды за главу - разводим по состоянию квеста
			if (PChar.TwoSisters == "3")
			{
				dialog.text = "Живой. ...(смотрит на повязку)... Не спрашиваю. Садись и рассказывай.";
				link.l1 = "Медальон. Тебе он что-нибудь говорит?";
				link.l1.go = "17";
				break;
			}
			if (PChar.TwoSisters == "6")
			{
				dialog.text = "Все четверо на месте, я их видел. Заведение открывается через неделю.";
				link.l1 = "Значит, я своё отработал" + GetSexPhrase("", "а") + ".";
				link.l1.go = "28";
				break;
			}
			if (PChar.TwoSisters == "1")
			{
				dialog.text = "Заходи, есть разговор. И сразу скажу: дело дурацкое.";
				link.l1 = "Договаривай.";
				link.l1.go = "1";
				break;
			}
			dialog.text = "Пока всё тихо. Заходи, если что.";
			link.l1 = "Зайду.";
			link.l1.go = "exit";
		break;

		// Завязка
		case "1":
			dialog.text = "Помнишь, ты возмущал" + GetSexPhrase("ся", "ась") + ", что в Сан-Хуане нет борделя?";
			link.l1 = "Не помню такого.";
			link.l1.go = "2";
			link.l2 = "Помню. И что?";
			link.l2.go = "2";
		break;

		case "2":
			dialog.text = "Теперь возмущаются корсары. Уже вторую неделю, и всё громче.";
			link.l1 = "Пусть возмущаются.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Пусть. Только после «пусть» у нас будет поножовщина в порту, а потом половина уйдёт к французам.";
			link.l1 = "И чего ты хочешь от меня?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Уговорить четырёх женщин переехать в Сан-Хуан и привезти их сюда.";
			link.l1 = "...(долгая пауза)... Ты серьёзно?";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Серьёзнее некуда. Мы сидим на пороховой бочке, " + GetSexPhrase("дорогой мой компаньон", "дорогая моя компаньонка") + ".";
			link.l1 = "Пошли кого-нибудь другого.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Другого они пошлют куда подальше. А тебя, может, и выслушают.";
			link.l1 = "Хорош комплимент.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Какой есть. К тому же ты обещал" + GetSexPhrase("", "а") + " помогать колонии, и я это слышал не один.";
			link.l1 = "Обещал" + GetSexPhrase("", "а") + ". Ладно, кто они?";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Список пираты составили сами. Четверо: Вики Хендерсон на Мартинике, Натали Ремис на Бермудах и сёстры Лус на Тортуге.";
			link.l1 = "Хендерсон - это которая в борделе Форт-де-Франса?";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Она самая. Скажешь, что от меня, - выслушает.";
			link.l1 = "И как их уговаривать? Подойти и позвать?";
			link.l1.go = "14";
		break;

		case "14":
			dialog.text = "Разберёшься. Просто так они не поедут, каждая попросит своё.";
			link.l1 = "То есть я буду работать ещё и на них.";
			link.l1.go = "15";
		break;

		case "15":
			dialog.text = "Всё может быть.";
			link.l1 = "...(тяжкий вздох)...";
			link.l1.go = "16";
		break;

		case "16":
			dialog.text = "Кончай вздыхать и берись за дело. Времени в обрез.";
			link.l1 = "...(уйти)...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TwoSistersStart");
		break;

		// Медальон сатаниста
		case "17":
			dialog.text = "...(берёт медальон)... Говорит. Откуда он у тебя?";
			link.l1 = "С тела в доме сестёр Лус. Тело потом исчезло.";
			link.l1.go = "18";
		break;

		case "18":
			dialog.text = "Тогда слушай. Такие носит одна секта, они называют себя аниматистами. Известно про них немного и всё скверное.";
			link.l1 = "Где их искать?";
			link.l1.go = "19";
		break;

		case "19":
			dialog.text = "Лет пятнадцать назад их логово стояло у испанского Белиза. Тогда в округе начали пропадать люди, сперва по одному, потом десятками.";
			link.l1 = "Их разогнали?";
			link.l1.go = "20";
		break;

		case "20":
			dialog.text = "Пытались. Гарнизон форта потерял три четверти состава, а Белиз - губернатора. После этого их больше не трогали.";
			link.l1 = "И никто не выяснил, кто они такие?";
			link.l1.go = "21";
		break;

		case "21":
			dialog.text = "Новый губернатор объявил сто тысяч тому, кто выяснит причину исчезновений. Деньги забрал человек по имени Мерил Крено.";
			link.l1 = "Что он выяснил?";
			link.l1.go = "22";
		break;

		case "22":
			dialog.text = "Ничего. Написал бумагу про болотную лихорадку, получил награду, и люди пропадать не перестали.";
			link.l1 = "Крено жив?";
			link.l1.go = "23";
		break;

		case "23":
			dialog.text = "Жив и живёт в Белизе, дом рядом с портовым управлением. Если кто и знает про этот медальон, то он.";
			link.l1 = "Тогда я к нему.";
			link.l1.go = "24";
		break;

		case "24":
			dialog.text = "Только не в лоб, " + GetFullName(PChar) + ". Он не из тех, кто пугается.";
			link.l1 = "Ещё одно. Тот сатанист встал после того, как его убили.";
			link.l1.go = "25";
		break;

		case "25":
			dialog.text = "...(морщится)... Или не был убит. Мне такое рассказывали дважды, и оба раза рассказчик был пьян.";
			link.l1 = "Я был" + GetSexPhrase("", "а") + " трезв" + GetSexPhrase("", "а") + ".";
			link.l1.go = "26";
		break;

		case "26":
			dialog.text = "Потому и слушаю. Узнаешь что-нибудь - сообщи, а я подниму старые бумаги.";
			link.l1 = "Договорились.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TwoSistersLusQuestToBeliz");
		break;

		// Финал
		case "28":
			dialog.text = "Отработал" + GetSexPhrase("", "а") + ". Заведение открыто, корсары довольны, я тоже. ...(помолчав)... Про Крено, кстати, ты " + GetSexPhrase("был прав", "была права") + ".";
			link.l1 = "Что с ним?";
			link.l1.go = "29";
		break;

		case "29":
			dialog.text = "Ничего. Бумаги пятнадцатилетней давности подписаны его рукой, а больше искать нечего - ты его закопал" + GetSexPhrase("", "а") + ".";
			link.l1 = "Значит, кончено.";
			link.l1.go = "31";
		break;

		case "31":
			dialog.text = "Постой, не уходи. Пока тебя носило по морям, к нам пришла партия пушек.";
			link.l1 = "Каких пушек?";
			link.l1.go = "32";
		break;

		case "32":
			dialog.text = "...(тише)... Сорокадвухфунтовых. Не спрашивай откуда. Если хочешь - поставим тебе.";
			link.l1 = "Хочу.";
			link.l1.go = "33";
		break;

		case "33":
			dialog.text = "Тогда я шепну плотнику на верфи. Скажешь ему, когда будешь готов.";
			link.l1 = "Я готов" + GetSexPhrase("", "а") + " прямо сейчас.";
			link.l1.go = "34";
		break;

		case "34":
			dialog.text = "...(усмехается)... Само собой. Тогда две вещи. Корабль нужен не ниже второго класса, и поставим их один раз - снимешь, обратно уже не наденешь.";
			link.l1 = "Понял" + GetSexPhrase("", "а") + ". Спасибо, Алехон.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("TwoSistersEnd");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
