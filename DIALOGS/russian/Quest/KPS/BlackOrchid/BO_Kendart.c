// Gregg: Алехон Кендарт - трилогия «Чёрная Орхидея», финал главы 5 (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\blackorchid.c
// Грот Теркса. Последний обладатель Орхидеи ждал того, кто соберёт Меритор:
//   1-3   - передача Орхидеи;
//   4-6   - чем она была и что от неё осталось;
//   6a-6b - посев: кого-то взяли вместо него, кто Орхидею и не искал (см. ниже);
//   7-9   - Меритор ушёл к новым соискателям, уничтожить Орхидею Кендарт не умеет;
//   10    - прощание, выход в бой (DestinyGiftFinalBattle).
// Узел 1 выставляет логика. Кендарт остаётся в мире и переходит в главы 6-9,
// поэтому «First time» - заглушка, её займёт диспетчер следующих глав.
//
// Gregg: ТРИ отступления от оригинала, оба принципиальные.
// 1. В К:ПС остаток силы Орхидеи - два месяца полной неуязвимости, после чего она
//    становится простым камнем. У нас Орхидея - оберег (снижение урона плюс одно
//    спасение от смертельного удара, см. BlackOrchid_IsWorn в blackorchid.c), и это
//    объясняется его же работой: он стёр её почти до конца, остаток скромен, но вечен.
// 2. В оригинале ГГ обещал через два месяца уничтожить Орхидею или спрятать её.
//    Обещания нет: глава 6 у нас идёт иначе, настоящая Орхидея остаётся у игрока,
//    и давать зарок, который мы не исполним, незачем. Вопрос оставлен открытым.
// 3. Узлы 6a-6b - НАШЕ добавление, в оригинале их нет. Оригинальный Кендарт молчит
//    о своём мотиве до самой главы 6, где выясняется, что испанцы, разыскивая его,
//    взяли и запытали до смерти его брата (Alehon Kendart.c, узел SpanishGenerosity_9).
//    Из-за этого его разворот в шестой главе - «продадим Орхидею Испании» - выглядит
//    подменой характера. Здесь мы кладём зацепку: кого-то взяли вместо него, и этот
//    кто-то Орхидею не искал. Ни нации, ни родства, ни имени - иначе разворот
//    в главе 6 перестанет быть разворотом. Заодно объясняется, почему он живёт
//    в гроте. Реплика узла 7 про «чтобы Орхидея досталась вам, а не Испании» тоже
//    наша: в главе 6 игрок процитирует её Кендарту в лицо.
//
// Gregg: Кендарт переходит с «ты» на «вы», когда речь идёт не о деле, а о природе
// Орхидеи - так было и в оригинале, это его манера.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	string sName = PChar.name;
	string sFullName = GetFullName(PChar);


	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Удачи тебе, " + sName + ".";
			link.l1 = "И вам, Алехон.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "...(тихий, мягкий голос)... " + sFullName + ". Я знал, что это случится. Знал, что найдёшь меня именно ты.";
			link.l1 = "...(властно)... Чёрная Орхидея. Отдай её мне. Немедленно.";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Отдам, " + sName + ". Но прежде спрошу. Готов" + GetSexPhrase("", "а") + " ли ты стать её " + GetSexPhrase("хозяином", "хозяйкой") + "? Готов" + GetSexPhrase("", "а") + " ли к тому, что за тобой пойдут другие соискатели - и не остановятся?";
			link.l1 = "" + GetSexPhrase("Готов", "Готова") + ". Отдавай.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "С этой минуты ты - " + GetSexPhrase("хозяин", "хозяйка") + " Чёрной Орхидеи.";
			link.l1 = "...(разглядывая Орхидею)... И это всё? Обычный камень в оправе.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Теперь - да. Все годы, что Орхидея была у меня, я потратил на то, чтобы свести её силу на нет. И почти преуспел, чем горжусь больше всего в жизни. То, что ты держишь, - тень прежней Орхидеи.";
			link.l1 = "Тень? Так она вообще хоть на что-нибудь годится?";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Годится. Надень её - и клинок, что должен был рассечь тебя надвое, оставит царапину. А однажды, когда удар всё же окажется смертельным, она не даст тебе упасть. Один раз. Потом ей нужно время, чтобы собраться с силами. Это всё, что от неё осталось, и это немало.";
			link.l1 = "Немало? Мне говорили, что Орхидея делает человека неуязвимым.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Делала. И потому убивала. Чёрная Орхидея несёт смерть даже в руках того, кто не рвётся к власти, - а я не рвался. Сколько людей полегло, пока вы её искали? Сколько ляжет ещё? Она делает убийц из добрых людей, стоит им понять, на что они способны, ею владея. Я отнял у неё эту возможность. Оставил ровно столько, чтобы хозяин выжил, и ни каплей больше.";
			link.l1 = "Вы говорите так, будто платили за это сами.";
			link.l1.go = "6a";
		break;

		case "6a":
			dialog.text = "Платил. И платили не только те, кто её искал. Однажды её искали через меня - меня не нашли и взяли того, кто про Орхидею слыхом не слыхивал. Ему было нечего рассказать. Спрашивали долго.";
			link.l1 = "Кто это был?";
			link.l1.go = "6b";
		break;

		case "6b":
			dialog.text = "...(долгая пауза)... Простите. Я об этом не говорю. Скажу только, что живу в гроте на голом острове не из любви к сырости.";
			link.l1 = "...(тихо)... Значит, всё это было ради оберега на шею.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Всё это было ради того, чтобы Орхидея досталась вам, а не Испании. А Меритор своё отслужил: как только Орхидея легла вам в руку, он исчез из вашего кармана. Он снова разошёлся на семь частей и разлетелся по Карибам - ждать следующего.";
			link.l1 = "Следующего? Значит, за мной придут.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Придут. И будут приходить, пока Орхидея существует.";
			link.l1 = "Тогда помогите мне избавиться от неё, Алехон. Вы прожили с ней годы - вы должны знать как.";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Не знаю, " + GetHeroLastName() + ". И не советую пробовать наугад - те, кто пробовал, умирали раньше, чем Орхидея успевала поблекнуть. Я сделал что мог, дальше решать тебе. А сейчас я тебя оставлю.";
			link.l1 = "Оставите? И как же вы отсюда выйдете?";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Я научился уходить и без Орхидеи, " + GetHeroLastName() + ". Удачи. Прощай.";
			link.l1 = "Нет, постойте!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DestinyGiftFinalBattle");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
