			link.l1.go = "26";
		break;

		case "26":
			dialog.text = "Потому что Рик Фишер прятал его там, где никому не придёт в голову искать: у беглых с каменоломен. Они сторожат его восьмой год и открыть не могут, потому что ключ был у Брюса.";
