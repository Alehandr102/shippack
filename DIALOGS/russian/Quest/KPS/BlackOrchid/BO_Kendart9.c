			AddDialogExitQuestFunction("FindAndDestroyFindUnlocker");
		break;

		case "25":
			dialog.text = "Разобрал. Фишер-младший вёл записи аккуратно, за это ему спасибо. Ключ от сундука, и сундук этот стоит в пещере у Куманы.";
