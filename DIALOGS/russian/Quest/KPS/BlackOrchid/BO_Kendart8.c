// Gregg: Алехон Кендарт - «Чёрная Орхидея», глава 8 «Рауль Эсперанто».
// Логика - Program\Quests\reaction_functions\blackorchid.c.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Я работаю. Загляни попозже.";
			link.l1 = "Не буду мешать.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "Вспомнил. Тридцать лет держал в голове и не мог достать, а тут вспомнил сразу и целиком. Садись.";
			link.l1 = "Где ты видел этот знак?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "На парусе. Мне было тридцать, я только приехал на Карибы и был полон намерений объяснить тут всё. Наша бригантина шла на Невис, и навстречу вышел линкор. На фоке у него был череп в кольце из костей.";
			link.l1 = "Тот же знак, что на часах.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Тот же. Линкор принадлежал Тони Андерсену. Его звали Беспощадным, и не за красоту слога.";
			link.l1 = "Андерсен. Тот, который стрелял по Гаване?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Он. Один залп, чтобы испанцы поторопились с выкупом. Наш капитан принял бой, и это было последнее, что он сделал. Уцелевших Андерсен приказал перебить всех.";
			link.l1 = "Всех, кроме тебя.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Кроме меня. Я думал - из-за очков и вида. Оказалось, ему нужен был человек, умеющий читать. Меня привели к нему в каюту и объяснили, что я буду делать оружие.";
			link.l1 = "Оружие. Песочные часы.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Похоже, что они. Работать я должен был не один, а с испанцем по имени Рауль Эсперанто. И вот что важно, " + PChar.name + ". Я не понимал ни слова из того, чем он занимался. Он мог сказать это Андерсену в первый же день.";
			link.l1 = "Но не сказал.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Не сказал. Полгода он делал мою работу за меня и молчал. Потом был туман, англичане и абордаж. Меня вытащили без сознания.";
			link.l1 = "А Андерсен?";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Убит. Рауля везли на том же корабле, что и меня, но говорить нам не дали: он был испанец и пленный. Мы обменялись двумя фразами за всю дорогу, и одну из них я помню до сих пор.";
			link.l1 = "Какую?";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Он сказал: «Если их найдут, не разбивайте». Я тогда не понял, о чём это. Теперь у меня на столе лежит вещь со знаком Андерсена, и я, кажется, начинаю понимать.";
			link.l1 = "Ты пробовал их сломать?";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "...(отводит глаза)... Пробовал. Не бьются, не разбираются и не тонут. Стыдно признаться, но я даже топил их в бухте. Они вернулись ко мне на стол.";
			link.l1 = "Вернулись?";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Я не буду это обсуждать. Нам нужен Рауль. Он единственный, кто знает про эти часы всё. Найди его и расспроси, а лучше привези сюда.";
			link.l1 = "Где его искать?";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "На Невисе. Его бросили в тюрьму Чарльстауна, как только сгрузили с корабля. Я понимаю, что тридцать лет - это тридцать лет, и что мы, скорее всего, найдём там только запись в книге. Но другой зацепки нет.";
			link.l1 = "Значит, Невис.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("RaulEsperantoStart");
		break;

		case "13":
			dialog.text = "...(встаёт)... Живой. Ты его действительно привёз. Долго искал?";
			link.l1 = "Дольше, чем рассчитыва" + GetSexPhrase("л", "ла") + ". Но всё это время был" + GetSexPhrase("", "а") + " уверен" + GetSexPhrase("", "а") + ", что он жив.";
			link.l1.go = "14";
		break;

		case "14":
			dialog.text = "И был прав. Ладно, потом расскажешь всё по порядку, а пока...";
			link.l1 = "Погоди. По дороге я встретил" + GetSexPhrase("", "а") + " кое-кого, кого не должно было быть.";
			link.l1.go = "15";
		break;

		case "15":
			dialog.text = "Кого?";
			link.l1 = "В тюрьме Чарльстауна есть призрак. Джо Ньюмен, бывший заключённый. Пятьдесят лет как.";
			link.l1.go = "16";
		break;

		case "16":
			dialog.text = "Не слыхал. И что призрак?";
			link.l1 = "Он не хотел разговаривать. Пришлось убедить его клинком.";
			link.l1.go = "17";
		break;

		case "17":
			dialog.text = "...(медленно садится обратно)... Ты драл" + GetSexPhrase("ся", "ась") + " с призраком. И победил" + GetSexPhrase("", "а") + ".";
			link.l1 = "Тяжело, но да.";
			link.l1.go = "18";
		break;

		case "18":
			dialog.text = "Это невозможно. Призраки бессмертны, на то они и призраки.";
			link.l1 = "Мой был смертный. Я проверил" + GetSexPhrase("", "а") + ".";
			link.l1.go = "19";
		break;

		case "19":
			dialog.text = "...(долго молчит)... Хорошо. Что было дальше?";
			link.l1 = "Он рассказал про Рауля и исчез. Всё.";
			link.l1.go = "20";
		break;

		case "20":
			dialog.text = "Тогда либо призраков можно убивать, либо он был не призрак. Второе мне нравится больше, но объясняет меньше.";
			link.l1 = "Давай сначала часы, а потом призраки.";
			link.l1.go = "21";
		break;

		case "21":
			dialog.text = "Часы придётся отложить. Рауль совсем плох: сначала инквизиция, потом многодневное плавание, после которого ему стало хуже, а не лучше.";
			link.l1 = "Сколько ждать?";
			link.l1.go = "22";
		break;

		case "22":
			dialog.text = "До завтра. Сегодня он не скажет ни слова, а со мной, даст бог, поговорит. И, " + PChar.name + ", ещё одно. Тридцать лет я был уверен, что остался жив из-за очков. Оказывается, из-за того, что чужой человек полгода молчал.";
			link.l1 = "Теперь вы знаете, кому обязаны. Завтра зайду.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("RaulEsperantoEnd");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
