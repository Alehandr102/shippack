// Gregg: губернатор Сантьяго - трилогия «Чёрная Орхидея» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\blackorchid.c
// Это КЛОН настоящего мэра: тот же облик и то же имя, но отдельный персонаж
// в клон-городе. Настоящий губернатор Сантьяго остаётся жив.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Что вам угодно?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "А, сеньор капитан. Наслаждайтесь триумфом. Наслаждайтесь - недолго вам осталось.";
			link.l1 = "И вам того же, Хосе. Если ваши люди в форте не сдадутся по нашему требованию, боюсь, мне придётся убить и вас, и сеньору Матильду. Как вам такой расклад?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Капитан, выйдите на пирс и всмотритесь в горизонт. Видите три белые точки? Это эскадра адмирала Меркеса, до порта ей пять-шесть часов. Выход в джунгли держат наши солдаты и десяток королевских пушек. Как видите, выхода у вас нет.";
			link.l1 = "Выход есть всегда, Хосе. Пишите ультиматум коменданту форта: «Обеспечить беспрепятственный выход из города капитану " + GetMainCharacterNameDat() + " и его людям. В противном случае губернатор Сантьяго и сеньора Матильда будут убиты». И печать с подписью внизу.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Я не буду этого писать, сеньор капитан. Можете убить меня прямо сейчас, если вам угодно. Моя смерть ничего не изменит.";
			link.l1 = "Зато доставит мне огромное удовольствие. А как насчёт Матильды, Хосе? Или вы забыли, что обязаны защищать её всеми возможными способами?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Позвольте кое-что объяснить. Матильда - отработанный материал. Её постоянные неудачи вынудили нас искать замену, и эта замена прибудет в Сантьяго на флагмане адмирала Меркеса. Смерть Матильды неизбежна, это вопрос времени: яд, подмешанный в вино за обедом, подействует через час, самое большее полтора. Моя смерть тоже вопрос времени - я серьёзно болен и протяну не больше двух дней.";
			link.l1 = "Ты лжёшь, испанская тварь!";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Нет, сеньор капитан. Всё сказанное - правда. Верьте или нет, это ничего не изменит. Вы в ловушке, и всё, что вам осталось, - ждать своей смерти.";
			link.l1 = "Это мы ещё посмотрим, Хосе. А теперь говори: где Матильда?";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Мне и самому хотелось бы это знать. Когда начался штурм, она исчезла бесследно. Впрочем, жить ей осталось недолго. Хм... ...(задумался)... Знаете, капитан, до чего приятно бывает, когда в жизни выходит всё задуманное. Когда готов уйти в мир иной, зная, что здесь тебя уже ничто не держит. Когда видишь перед собой капитана " + GetMainCharacterNameGen() + " - самого успешного соискателя, - загнанного в угол и... как бы это сказать.";
			link.l1 = "Не утруждай себя, Хосе.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("MysteriousArtefactKillSantiagoGovernor");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
