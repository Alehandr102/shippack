// Gregg: Фернандо Эстикос - трилогия «Чёрная Орхидея», глава 5 (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\blackorchid.c
// Спившийся компаньон Бернальдинио Торангеры, сидит в таверне Портобелло:
//   1     - зовёт выпить, ГГ подсаживается (DestinyGiftInPortoBelloTavern);
//   2-7   - что случилось со «Стервятником» и где видели его остов;
//   7     - выход, задание найти остов (DestinyGiftFindBernaldinioShip).
// Узлы 1 и 2 выставляет логика, остальные идут по цепочке.
// Gregg: в оригинале капитан видел остов «где-то на Мэйне» без подробностей, и игрока
// отправляли обыскивать всё побережье. У нас бухта с остовом доступна только пешком,
// с моря к ней не подойти, поэтому Фернандо называет место: мыс Несбывшихся Надежд,
// за Дес-Мойнесом. Иначе игрок ушёл бы искать точку на глобальной карте, которой нет.
// Gregg: ГГ бывает женщиной - формы через GetSexPhrase.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);


	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Удачи вам, кэп!";
			link.l1 = "И тебе не хворать. И заканчивай уже пить.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "Выпить со мной хочешь? Ну садись, чего " + GetSexPhrase("встал", "встала") + "!";
			link.l1 = "...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DestinyGiftInPortoBelloTavern");
		break;

		case "2":
			dialog.text = "Трактирщик! Рома! За что пить будем, кэп?";
			link.l1 = "Напиться всегда успеешь, Фернандо. Расскажи лучше, что случилось с твоим компаньоном, с Бернальдинио Торангерой.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Не знаю я, кэп. В последнее наше совместное плавание разразился шторм страшной силы и развёл нас в стороны. Дальше я шёл один, а Бернальдинио в порт назначения так и не пришёл. Ни он, ни «Стервятник». Хотя...";
			link.l1 = "Хотя что?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Слыхал я кое-что от одного торговца в таверне Пуэрто-Рико. Говорит, видел сгнивший остов «Стервятника» на берегу Мэйна. Выходит, в тот злополучный день корабль выбросило на камни. Только не верю я в это.";
			link.l1 = "Почему? Корабли и посильнее выбрасывало штормом.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Знаю. Но Бернальдинио управлялся с судном и в самую разрушительную бурю. Он бы не дал выбросить себя на берег.";
			link.l1 = "А где именно тот торговец видел «Стервятника»?";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "На побережье Мэйна, у мыса Несбывшихся Надежд. Глухое место: с моря к нему не подойти, только берегом, из джунглей за Дес-Мойнесом. А тебе-то это зачем? Ты что, " + GetSexPhrase("собрался", "собралась") + " искать его корабль?";
			link.l1 = "Собираюсь. У Бернальдинио была одна вещь, которая мне нужна, и остов «Стервятника» - моя единственная зацепка.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Тогда попутного ветра тебе, кэп.";
			link.l1 = "И тебе попутного ветра, Фернандо.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DestinyGiftFindBernaldinioShip");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
