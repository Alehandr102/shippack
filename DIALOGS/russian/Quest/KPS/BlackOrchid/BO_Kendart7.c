// Gregg: Алехон Кендарт - «Чёрная Орхидея», глава 7 «Маленький ублюдок».
// Логика - Program\Quests\reaction_functions\blackorchid.c.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			// Gregg: часы найдены - Кендарт ждёт именно с ними, других поводов нет
			if (PChar.SmallMongrel == "17")
			{
				dialog.text = "Ну наконец-то. Что " + GetSexPhrase("привёз", "привезла") + "?";
				link.l1 = "Вот это. Сняли с «Маленького ублюдка».";
				link.l1.go = "16";
			}
			else
			{
				dialog.text = "Я работаю. Загляни попозже.";
				link.l1 = "Не буду мешать.";
				link.l1.go = "exit";
			}
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "А, это ты. Хорошо. Садись, разговор будет долгий... и, боюсь, неприятный.";
			link.l1 = "Неприятный чем?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Тем, что я собираюсь просить тебя о вещи, которая может тебя убить. И я не могу обещать, что пойму, отчего именно.";
			link.l1 = "Меня и раньше пытались убить. Пока не вышло.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Пытались люди. Тут, возможно, не люди. Я, знаешь ли, тридцать лет держусь того, что необъяснимого не бывает, бывает необъяснённое. В этом деле я впервые не уверен.";
			link.l1 = "Говори по существу, Алехон.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "По существу. Ты слыша" + GetSexPhrase("л", "ла") + " про «Маленького ублюдка»?";
			link.l1 = "Нет. Человек или судно?";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Судно. Тяжёлый фрегат. Имя ему дали испанцы, и не от большой любви. Лет пятнадцать назад караван из двух флейтов шёл из Маракайбо в Белиз и у бухты Аматике встретил его. Пустой, в дрейфе, без единой души на борту.";
			link.l1 = "И они, конечно, взяли его призом.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Взяли. Высадили тридцать два человека призовой команды и пошли дальше. Наутро вся эта команда висела на реях. Тридцать два тела. Никто ничего не слышал ночью, а море было тихое.";
			link.l1 = "Кто-то же должен был это рассказать.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Один матрос. Он добрался до Белиза, я его и слушал. Говорить он почти не мог, а через две недели умер, и лекарь не нашёл, от чего.";
			link.l1 = "Одна история - это одна история.";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Именно так я тогда и рассудил. А потом, годы спустя, мне рассказал то же самое пират по имени Джекоб. С одной разницей: его призовую команду не вешали. Перестреляли и покидали в трюм.";
			link.l1 = "И Джекоб уцелел один.";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Один. И испанец тогда уцелел один. Понимаешь, что мне не нравится? Не мертвецы. Мертвецов в море хватает. Мне не нравится, что всякий раз остаётся ровно один рассказчик.";
			link.l1 = "Будто кому-то нужно, чтобы историю пересказали.";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "...(помолчав)... Вот эту мысль я себе запретил думать. У тебя она пришла за минуту.";
			link.l1 = "И где сейчас этот фрегат?";
			link.l1.go = "11";
		break;

		case "11":
			dialog.text = "Месяц назад мне сказали, что он у Джекмена. Стоит на берегу у пиратского поселения на Бермудах, и при нём четверо сторожей. Джекмен прижимист и не дурак: за пустой корпус он четверых кормить не стал бы.";
			link.l1 = "Значит, надо его купить.";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Купить и обыскать. Всё: трюм, каюты, обшивку. Если ничего не найдёшь - веди его на буксире в Сан-Хуан, разберём по доске. Только, прошу тебя, не ночуй на нём и не оставляй на нём своих людей.";
			link.l1 = "Не оставлю.";
			link.l1.go = "13";
		break;

		case "13":
			dialog.text = "И ещё. Если что-то пойдёт не так, брось его и уходи. Я найду другой способ. А другого тебя я не найду.";
			link.l1 = "Сентиментально для учёного.";
			link.l1.go = "14";
		break;

		case "14":
			dialog.text = "...(сухо)... Это не сентиментальность, а арифметика. Ну, ступай.";
			link.l1 = "Иду на Бермуды.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SmallMongrelStart");
		break;

		case "16":
			dialog.text = "...(разглядывая часы против света)... Песочные часы. Старая работа, серебро потемнело. И чем же они тебя так заняли?";
			link.l1 = "Посмотри на колбу. Череп в кольце из костей.";
			link.l1.go = "17";
			TakeNItems(PChar, "DamnedClock", -1);
		break;

		case "17":
			dialog.text = "Вижу. Череп со скрещёнными костями я знаю, его на любом флаге малюют. А вот кольцо...";
			link.l1 = "Я такого нигде не встречал" + GetSexPhrase("", "а") + ".";
			link.l1.go = "18";
		break;

		case "18":
			dialog.text = "А я, кажется, встречал. Очень давно. И вот что скверно: помню картинку, а где видел - не помню совершенно.";
			link.l1 = "Постарайся вспомнить.";
			link.l1.go = "19";
		break;

		case "19":
			dialog.text = "Постараюсь. Своё ты " + GetSexPhrase("сделал", "сделала") + ", дальше моя очередь. Только память по приказу не работает, даже по моему собственному. Дай мне неделю.";
			link.l1 = "Неделя у тебя есть.";
			link.l1.go = "20";
		break;

		case "20":
			dialog.text = "Тогда до встречи. И ещё, " + PChar.name + ". Спасибо, что не " + GetSexPhrase("оставил", "оставила") + " их там висеть в моей голове одних.";
			link.l1 = "Бывай, Алехон.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SmallMongrelEnd");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
