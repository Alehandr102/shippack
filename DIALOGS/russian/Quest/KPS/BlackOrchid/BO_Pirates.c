// Gregg: Мэтью Грехом, командир отряда корсаров - трилогия «Чёрная Орхидея»
// (перенос из К:ПС). Логика - Program\Quests\reaction_functions\blackorchid.c
// Встреча в джунглях Кубы перед штурмом Сантьяго. Грехом собирается штурмовать
// форт в лоб, ГГ предлагает взять беззащитный город - и получает отказ.
// В оригинале эти узлы жили в общем файле Pirates.c вместе с посыльным с Бермуд;
// посыльный у нас вынесен в BO_Messenger.c.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	string sName = GetHeroLastName();

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Чего надо?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "Рад приветствовать вас, капитан " + sName + "! Я Грехом, Мэтью Грехом, командир отряда корсаров. Ребята у меня отличные вояки, но без вашей помощи нам не обойтись. Риск, конечно, велик, но если удастся освободить Джейсона - мы заплатим вам сто тысяч пиастров. Времени мало, решайтесь.";
			link.l1 = "Атаковать форт второй раз бессмысленно. Испанцы отлично подготовились к обороне, несколько пушек держат дорогу, по которой вы пойдёте, и значительные силы из города переброшены туда же.";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Не продолжайте, капитан " + sName + ", я уже понял: помогать вы не станете. Не настаиваю. Но подумайте ещё раз, прежде чем отказываться. Сто тысяч - деньги немалые.";
			link.l1 = "Напротив, помочь я хочу. Только план у меня другой.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Выкладывай, " + sName + ". Только быстро.";
			link.l1 = "Предлагаю ударить по самому городу. Основные силы испанцев сейчас в форте, а Сантьяго остался без прикрытия. Пока они держат оборону и ждут нападения, мы возьмём беззащитный город, пробьёмся в резиденцию и захватим губернатора, а вместе с ним - одну очень влиятельную особу, сеньору Матильду. Дальше два пути. Первый: мы грозим убить обоих, если испанцы не сложат оружие и не выдадут Джейсона.";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Испанцы не идиоты. Они пойдут на штурм города, и тогда...";
			link.l1 = "Это и есть второй путь. Если они пойдут на штурм, Джейсона нам не освободить, и придётся отходить морем на Пуэрто-Принсипе.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Неужели ты настолько глуп, " + sName + ", чтобы надеяться, что я на это соглашусь?";
			link.l1 = "А неужели ты настолько глуп, Грехом, чтобы угробить себя и всех своих людей об отлично укреплённый форт? Ты всерьёз думаешь, что сотня корсаров выстоит против противника, который превосходит вас и числом, и вооружением?";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Готов поспорить, что с твоей помощью или без неё я пробьюсь в ту тюрьму, капитан " + sName + ".";
			link.l1 = "В таком случае могу лишь пожелать тебе удачи, Грехом.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "...(злобно)... И тебе удачи, капитан " + sName + ". Прощай.";
			link.l1 = "Счастливо оставаться.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("MysteriousArtefactInSantiagoJungleDialog");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
