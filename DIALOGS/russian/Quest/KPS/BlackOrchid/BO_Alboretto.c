// Gregg: Эмилио Альборетто - «Чёрная Орхидея», глава 6 «Испанская щедрость» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\blackorchid.c
// Оригинал - DamnedDestiny\SpanishGenerosity\Emilio Alboretto.c.
//   1-6   - таверна Сантьяго, первый торг, ГГ отказывается продавать;
//   20-25 - второй заход: цена названа - Сан-Хуан и двадцать пять миллионов;
//   30-34 - палуба «Андромеды» после отбитой засады;
//   40-44 - ратуша Сантьяго: колония очищена, задаток на руки.
//
// Gregg: ОТСТУПЛЕНИЯ. Лестница торга оригинала (5 -> 10 -> ГГ просит 200 -> 25) сжата:
// двести миллионов и «да вы охренели что ли» из оригинала выброшены, торг идёт короче
// и суше. Двадцать пять миллионов остаются в реплике, но платят из них только задаток -
// см. BO_SG_DEPOSIT в логике. Модель - PGG_Espinosa_0 (решение пользователя).

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	string sLastName = GetHeroLastName();


	switch (Dialog.CurrentNode)
	{
		case "First time":
			dialog.text = "Всё, о чём мы уговорились, в силе, капитан. Мне добавить нечего.";
			link.l1 = "И мне.";
			link.l1.go = "exit";
			NextDiag.TempNode = "First time";
		break;

		case "1":
			dialog.text = "...(поднимается навстречу)... Капитан " + sLastName + ". Эмилио Альборетто, к вашим услугам. Садитесь, прошу вас. Разговор у меня короткий, но не из тех, что ведут стоя.";
			link.l1 = "Вы здесь по чьему поручению, сеньор Альборетто?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Испанской короны. Не будем играть в прятки, капитан: нам известно, что Чёрная Орхидея у вас. Корона хочет её купить.";
			link.l1 = "А если я скажу, что понятия не имею, о чём вы?";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Тогда я извинюсь и уйду. Но вы этого не скажете, иначе не сели бы за этот стол.";
			link.l1 = "...(усмехаясь)... Допустим. Сколько?";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Пять миллионов пиастров. Золотом, где вам будет угодно.";
			link.l1 = "Пять миллионов. За вещь, за которой полгода охотилась половина Карибов.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "...(без паузы)... Десять. И это не последнее слово, капитан, это второе.";
			link.l1 = "Сеньор Альборетто, я вижу, вам велено привезти Орхидею любой ценой. Оттого и разговор бессмысленный.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Назовите цену сами. Любую.";
			link.l1 = "Не сегодня. Орхидея не продаётся. Прощайте, сеньор.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SpanishGenerosityExitFromTavern");
		break;

		case "20":
			dialog.text = "...(медленно поднимается)... Капитан. Признаться, я не ждал вас увидеть.";
			link.l1 = "Я " + GetSexPhrase("передумал", "передумала") + ", сеньор Альборетто. Орхидея продаётся.";
			link.l1.go = "21";
		break;

		case "21":
			dialog.text = "...(садится)... Слушаю вас очень внимательно.";
			link.l1 = "Двадцать пять миллионов пиастров. И колония Сан-Хуан в мою собственность.";
			link.l1.go = "22";
		break;

		case "22":
			dialog.text = "...(долгая пауза)... Деньги - вопрос решаемый. Но колония, капитан? Вы просите у короны кусок короны.";
			link.l1 = "Я прошу за вещь, которой в мире одна штука. Торговаться не буду: цена одна и целиком.";
			link.l1.go = "23";
		break;

		case "23":
			dialog.text = "Вы понимаете, что Сан-Хуан придётся не просто передать, а очистить? Гарнизон, чиновники, флот - всё.";
			link.l1 = "Понимаю. И до тех пор камня вы не получите.";
			link.l1.go = "24";
		break;

		case "24":
			dialog.text = "...(потирает переносицу)... В Севилью я отписал ещё до первого нашего разговора, капитан: знал, чем кончится торг. Ответ будет ждать меня на «Андромеде» у Санта-Каталины. Приходите туда - там и услышите его первым.";
			link.l1 = "Отчего же не здесь, за столом?";
			link.l1.go = "25";
		break;

		case "25":
			dialog.text = "Оттого, капитан, что о вашей Орхидее в этой таверне знаю не только я. В море спокойнее. Мне так кажется.";
			link.l1 = "Значит, у Санта-Каталины. Буду.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SpanishGenerosityAlborettoInShore");
		break;

		case "30":
			dialog.text = "...(тяжело дыша, у фальшборта)... Я обязан вам жизнью, капитан. Ещё четверть часа - и «Андромеду» разобрали бы на доски.";
			link.l1 = "Это были не испанцы, сеньор.";
			link.l1.go = "31";
		break;

		case "31":
			dialog.text = "Не испанцы. Это были те, кому Орхидея нужна не меньше короны, а платить они не собирались вовсе. Я же говорил, что в той таверне знаю не только я.";
			link.l1 = "Ответ из Севильи вы привезли?";
			link.l1.go = "32";
		break;

		case "32":
			dialog.text = "Привёз. Корона согласна. Сан-Хуан и двадцать пять миллионов - на ваших условиях, целиком.";
			link.l1 = "Не " + GetSexPhrase("думал", "думала") + ", что согласятся так легко.";
			link.l1.go = "33";
		break;

		case "33":
			dialog.text = "...(отводит глаза)... Легко, капитан, они соглашаются только на то, что рассчитывают вернуть. Не спрашивайте меня больше, я и так сказал лишнее. На очищение города нужно три недели.";
			link.l1 = "Где встречаемся?";
			link.l1.go = "34";
		break;

		case "34":
			dialog.text = "В ратуше Сантьяго, через три недели. К тому дню на Пуэрто-Рико не останется ни одного нашего солдата.";
			link.l1 = "Через три недели, сеньор Альборетто.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SpanishGenerosityPreSecondTimer");
		break;

		case "40":
			dialog.text = "Сан-Хуан пуст, капитан. Гарнизон, чиновники, оба сторожевых корабля - всё вышло вчера с утренним отливом. Город ваш.";
			link.l1 = "Быстро вы управились. Деньги?";
			link.l1.go = "41";
		break;

		case "41":
			dialog.text = "Задаток - миллион, вот он, счётом. Остальные двадцать четыре пойдут переводом через банкирский дом в Севилье: таких денег в колониальной казне нет и не бывало.";
			link.l1 = "Перевод. То есть бумага.";
			link.l1.go = "42";
		break;

		case "42":
			dialog.text = "Бумага испанской короны, капитан. Она стоит дороже золота, иначе Европа давно бы воевала телегами с монетой.";
			link.l1 = "...(сгребая счёт)... Хорошо. Камень?";
			link.l1.go = "43";
		break;

		case "43":
			dialog.text = "Оставьте его в тайнике на суше и передайте мне место. Я не притронусь к нему, пока последний наш солдат не сойдёт на берег в Гаване. Слово Альборетто.";
			link.l1 = "Место вы узнаете. Прощайте, сеньор.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("SpanishGenerosityDealDone");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
