// Gregg: Иеронимо Тавора, инквизитор Сантьяго - «Чёрная Орхидея», глава 8 «Рауль Эсперанто».
// Логика - Program\Quests\reaction_functions\blackorchid.c.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			// Gregg: три беседы: находка Рауля, Евангелие и трость. Разводим по состоянию.
			// Gregg: третья беседа - за тростью для Эсперанто
			// Gregg: не по состоянию "11" - оно ставится, когда Тавора согласился, то есть
			// ещё до спуска в подвал. Метку ставит сам Рауль, когда просит трость.
			if (CheckAttribute(PChar, "RaulEsperanto.Stick"))
			{
				dialog.text = "Он ещё здесь?";
				link.l1 = "Он не может идти. При аресте у него забрали трость.";
				link.l1.go = "30";
			}
			else
			{
			if (PChar.RaulEsperanto == "10")
			{
				dialog.text = "Вы вернулись быстрее, чем я рассчитывал.";
				link.l1 = GetSexPhrase("Я привёз", "Я привезла") + " то, что вы просили.";
				link.l1.go = "1";
			}
			else
			{
			// Gregg: строго по состоянию. На else тут была дыра: после разговора состояние
			// уходит в "7", и ветка заводилась снова, вешая ту же запись в журнал.
			if (PChar.RaulEsperanto == "6")
			{
				dialog.text = "Мир вам. Вы по делу или заблудились?";
				link.l1 = "По делу. В вашей тюрьме сидит старик, Рауль Эсперанто.";
				link.l1.go = "20";
			}
			else
			{
				dialog.text = "Мир вам. У меня служба, у вас, полагаю, тоже.";
				link.l1 = "Не буду мешать.";
				link.l1.go = "exit";
			}
			}
			}
			NextDiag.TempNode = "First time";
		break;

		case "20":
			dialog.text = "Сидит. Испанец, опыты, порошок из мумий, переписка с известным нам человеком на Гваделупе. Он вам зачем?";
			link.l1 = "Он нужен мне живым и снаружи.";
			link.l1.go = "21";
		break;

		case "21":
			dialog.text = "...(не удивившись)... Все чего-нибудь хотят. Я тоже. Только отпустить его я не могу: он записан не за мной.";
			link.l1 = "А кто здесь распоряжается, если не вы?";
			link.l1.go = "22";
		break;

		case "22":
			dialog.text = "В Сантьяго - я. Но Эсперанто внесён в бумаги трибунала, который идёт из Европы, и главный инквизитор сойдёт на берег со дня на день. Отпущу старика сам - отвечать буду перед ним.";
			link.l1 = "А если дать вам повод?";
			link.l1.go = "23";
		break;

		case "23":
			dialog.text = "Повод мне и нужен. На Сан-Мартине живёт банкир по имени Ян Бозен. Двенадцать лет он держит вещь, которая принадлежит не ему.";
			link.l1 = "Что за вещь?";
			link.l1.go = "24";
		break;

		case "24":
			dialog.text = "Книга. Больше вам знать незачем, а мне спокойнее. Привезите мне Бозена, а лучше книгу, и старик выйдет отсюда в тот же день.";
			link.l1 = "Сан-Мартин, Мариго. Я" + GetSexPhrase(" понял", " поняла") + ".";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("RaulEsperantoFindBeausing");
		break;

		case "1":
			dialog.text = "Слушаю.";
			link.l1 = "Ян Бозен. Я знаю, где он и что у него было.";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "...(медленно откладывает перо)... Продолжайте.";
			link.l1 = "Он на моём корабле. А это то, ради чего вы его ищете.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "...(берёт книгу, открывает на середине, читает несколько строк, закрывает)... Она. Двенадцать лет.";
			link.l1 = "Бозен вам больше не нужен?";
			link.l1.go = "4";
			TakeNItems(PChar, "RaulEsperanto_Evangelie", -1);
		break;

		case "4":
			dialog.text = "Бозен был нужен нам ровно настолько, насколько у него лежала книга. Книга здесь. Значит, и он больше никому не должен.";
			link.l1 = "Значит, я верну его домой.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Возвращайте. И назовите вашу цену, капитан. Я не люблю оставаться должен: долг обязывает сильнее договора.";
			link.l1 = "В вашей тюрьме сидит старик. Рауль Эсперанто.";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "...(смотрит долго)... Испанец. Опыты, порошок из мумий, переписка с известным нам человеком на Гваделупе.";
			link.l1 = "Он мне нужен живым и снаружи.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Он был мне нужен, чтобы положить хоть что-то на стол перед трибуналом. Теперь мне есть чем встретить их, и это стоит дороже старика.";
			link.l1 = "Это «да»?";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Это «да». Забирайте его сегодня, пока я не передумал и пока бумаги ещё не ушли в Мадрид. И, капитан...";
			link.l1 = "Что?";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Не спрашивайте его, что он делал для Андерсена. Тридцать лет назад я задал этот вопрос человеку, который знал ответ, и с тех пор ищу книгу.";
			link.l1 = "...(молчит)...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("RaulEsperantoTalkWithEsperanto");
		break;

		case "30":
			dialog.text = "Трость? ...(выдвигает ящик стола)... Да, у меня. При аресте отбирают всё, а возвращать обычно уже некому.";
			link.l1 = "Сегодня есть кому.";
			link.l1.go = "31";
		break;

		case "31":
			dialog.text = "...(кладёт трость на стол)... Забирайте. И скажите ему, что я её не сломал. Ему это будет важнее, чем свобода, вот увидите.";
			link.l1 = "Скажу.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("RaulEsperantoGiveStick");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
