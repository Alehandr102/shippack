// Gregg: Аллен Гладстонн и Чёрный Мальчик - квест «Корабль обезьян» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\captainmonkey.c
// Узлы 1-5 - завязка у церкви Бас-Тера, 9-10 - Аллен в церкви Белиза,
// 11-13 - последняя встреча за воротами, 14-19 - Чёрный Мальчик на берегу.
// Узлов 6-8 из оригинала здесь нет: там Аллен приходил в грот обыскивать пленника
// и отбирал саблю, а мы вещи не отбираем - вместо него грот сторожат скелеты.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	string sIsland = PChar.CaptainMonkey.IslandID;
	sIsland = XI_ConvertString(sIsland + "Gen");

	string sGrotIsland;
	int iMoney;
	// Gregg: общий тумблер «убрать требования рангов у квестов». Читаем ЖИВЬЁМ,
	// как у Тилльманна и Сайфуса: галочка стоит - завязка открыта с первого ранга.
	int iRankReq = 1;
	if (!bQuestsRank) iRankReq = 13;

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Никто, никто не хочет мне верить... Все считают меня сумасшедшим...";
			link.l1 = "Это очень плохо...";
			link.l1.go = "exit";

			// Gregg: пока квест не взят - предлагаем завязку. Порог ранга тот же,
			// что CM_RANK_REQ в логике (13): дефайны в сегмент диалога не доезжают.
			// Ранг читаем напрямую: GetRank(PChar, 0) прибавляет ранг ГГ ещё раз внутри
			// и вернул бы удвоенное значение - порог сработал бы уже на седьмом ранге.
			if (PChar.CaptainMonkey == "0")
			{
				if (CheckAttribute(PChar, "CaptainMonkey.NotTrust"))
				{
					link.l1 = "Где, ты говоришь, это было - на траверсе " + sIsland + "?";
					link.l1.go = "4";
					link.l2 = "Это очень плохо...";
					link.l2.go = "exit";
				}
				else
				{
					if (sti(PChar.rank) >= iRankReq)
					{
						link.l1 = "О чём ты говоришь, бродяга?! Кто и во что отказывается верить?";
						link.l1.go = "1";
						link.l2 = "Это очень плохо...";
						link.l2.go = "exit";
					}
				}
			}
		break;

		case "1":
			dialog.text = "Никто не верит мне, даже священник, а ведь я говорю истинную правду, одну только правду...";
			link.l1 = "Да о чём ты бормочешь? Расскажи по порядку. Что с тобой приключилось?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "По порядку... Да какой уж тут порядок, сударь, когда тебя берёт на абордаж корабль с обезьянами на борту!";
			link.l1 = "Э-э, парень... Я вижу - ты действительно хлебнул лишнего.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Ничего подобного, " + GetAddress_FormToNPC(NPChar) + "! Хотите - верьте, хотите - нет, но я говорю истинную правду! В прибрежных водах " + sIsland + " мой торговый шлюп атаковал люггер с обезьянами на борту! С обезьянами, " + GetAddress_FormToNPC(NPChar) + "! Эти макаки словно заправские пираты разделались с моими матросами, а меня вышвырнули за борт, будто пустой бочонок из-под рома! Не спрашивайте меня, как я добирался до дома! Никто мне не верит, никто...";
			link.l1 = "Да-а, в такую историю может поверить лишь сумасшедший. Где, ты говоришь, это было - на траверсе " + sIsland + "?";
			link.l1.go = "4";
			link.l2 = "И ты хочешь, чтобы я поверил" + GetSexPhrase("", "а") + " в этот бред? По-моему, тебе стоит как следует прочистить мозги кружечкой забористого рома!";
			link.l2.go = "5";
		break;

		case "4":
			dialog.text = "Да, " + GetAddress_FormToNPC(NPChar) + ". Это было в прибрежных водах " + sIsland + ". Клянусь, я говорю чистую правду!";
			link.l1 = "Хорошо, я тебе верю.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("CaptainMonkeyStart");
		break;

		case "5":
			PChar.CaptainMonkey.NotTrust = true;
			dialog.text = "Никто, никто не хочет мне верить...";
			link.l1 = "...";
			link.l1.go = "exit";
		break;

		case "9":
			dialog.text = "Капитан, это вы?! Как вам удалось найти меня?!";
			link.l1 = "К чему эти глупые расспросы? По-моему, тебе лучше подумать о том, через сколько секунд твоя грешная душа взлетит на небо.";
			link.l1.go = "10";
		break;

		case "10":
			dialog.text = "Не станете же вы обнажать оружие в святом месте? Я думаю, вы не способны на подобное святотатство! Давайте выйдем за город - там я расскажу вам много интересного!";
			link.l1 = "Ну, пойдём.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("CaptainMonkeyFromChurchToTown");
		break;

		case "11":
			dialog.text = "Капитан, вы уже во второй раз заставляете меня удивляться! Как вы нашли меня на этот раз?!";
			link.l1 = "Надеюсь, что именно эта наша встреча станет последней, уважаемый любитель животных.";
			link.l1.go = "12";
		break;

		case "12":
			dialog.text = "Я понимаю - вы хотите заставить меня рассказать всё, что я знаю о капитане Маугли. Но даже под угрозой смерти я не стану этого делать. Если я распущу язык, Маугли найдёт меня где угодно, и тогда мне точно не жить. А в схватке с вами у меня есть хоть какие-то шансы.";
			link.l1 = "Боюсь тебя разочаровать, но ты выбрал самый короткий путь на тот свет.";
			link.l1.go = "13";
		break;

		case "13":
			dialog.text = "Посмотрим! Защищайтесь, капитан " + GetFullName(PChar) + "!";
			link.l1 = "...";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("CaptainMonkeyBattleWithAllen");
		break;

		case "14":
			dialog.text = UpperFirst(GetAddress_FormToNPC(NPChar)) + ", вы не дадите мне несколько монеток на пропитание?..";
			link.l1 = "Почему ты не найдёшь себе работу? Жить подаянием - не самая завидная участь.";
			link.l1.go = "15";
		break;

		case "15":
			dialog.text = "Дело в том, что я здесь живу не так давно, а всё моё детство прошло в джунглях, рядом с обезьянами. Я не владею никаким ремеслом, к тому же никого здесь толком не знаю - вот и не могу пока сам зарабатывать на хлеб насущный...";
			link.l1 = "В джунглях с обезьянами? Кто же научил тебя разговаривать? За всю свою жизнь я видел" + GetSexPhrase("", "а") + " только одну говорящую обезьяну - некоего капитана Маугли.";
			link.l1.go = "16";
		break;

		case "16":
			dialog.text = "Вы знаете капитана Маугли?! Обычно того, кто с ним познакомится, в скором времени ожидает незавидная участь! А вы, как я погляжу, живы и здоровы?!";
			link.l1 = "Так ты тоже его знаешь? Говори же!";
			link.l1.go = "17";
		break;

		case "17":
			dialog.text = "Ещё бы, я знал его ещё тогда, когда он был человеком - он и воспитывал меня. А с тех пор, как он заключил договор с нечистой силой и превратился в макаку, жестокость его не знала границ. Я больше не мог терпеть его издевательств и сбежал. Ну а как вам удалось выжить после свидания с ним, ведь он бессмертен?!";
			link.l1 = "Это длинная история - мне сохранили жизнь лишь для того, чтобы получить мои деньги, но, к счастью, мне удалось бежать. Так ты говоришь, он заключил договор с нечистой силой?";
			link.l1.go = "18";
		break;

		case "18":
			dialog.text = "Да, " + GetAddress_FormToNPC(NPChar) + ". Однажды он нашёл выброшенную на берег запечатанную бутылку и из любопытства вскрыл её... Освободившийся из заточения злобный демон сумел уговорить его пойти на это... Я не знаю, что вдруг на него нашло, но он решился на этот шаг. Зачем он согласился - до сих пор не пойму. Демон обещал Маугли бессмертие и поддержку со стороны всякой нечисти, а взамен потребовал наказывать смертью людей за один из самых невинных земных грехов - любопытство... Они подписали договор, и Маугли расписался на нём своей кровью. До тех пор, пока этот договор существует, Маугли бессмертен.";
			link.l1 = "Что значит - до тех пор, пока договор существует? Стало быть, его можно уничтожить?";
			link.l1.go = "19";
		break;

		case "19":
			iMoney = sti(PChar.money) / 100;
			if (iMoney > 10000) iMoney = 10000;
			AddMoneyToCharacter(PChar, -iMoney);

			sGrotIsland = CaptainMonkeyGetGrotIsland();
			dialog.text = "Это сделать не просто, " + GetAddress_FormToNPC(NPChar) + ". Вам очень повезло, что вы встретили меня - я расскажу, как до него добраться. Сундучок с договором Маугли спрятал в гроте, " + sGrotIsland + ". Сундучок надёжно охраняется всякого рода нечистью, но если вам удастся заполучить эту бумагу и предать её огню - договор будет расторгнут, Маугли потеряет бессмертие и станет бессилен!";
			link.l1 = "Да, мне действительно повезло, что я встретил" + GetSexPhrase("", "а") + " тебя... Возьми-ка эти " + iMoney + " монет и постарайся выучиться какому-нибудь ремеслу. Надеюсь, мы ещё увидимся!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("CaptainMonkeyFindContract");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
