// Gregg: Билл Метью и Бен Грегори - квест «Исчезновение людей» (перенос из К:ПС).
// Логика - Program\Quests\reaction_functions\disappearpeople.c
// Узлы 1-6 - рассказ спасённого штурмана, 7-9 - разговор с Грегори в пещере Барбадоса.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Что вам угодно?";
			link.l1 = "Ничего.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "Спасибо, что помогли мне, капитан - без вас они бы убили меня и забрали монету.";
			link.l1 = "О какой монете вы говорите?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Пожалуй, мне стоит рассказать вам свою историю. Когда-то я был штурманом на пиратском бриге ''Удачливый Джокер''. Однажды мы решили спрятать свою добычу в пещере Барбадоса и совершенно случайно наткнулись на древний клад Инков. Помимо драгоценностей, мы нашли шкатулку, в которой лежали пузырёк с какой-то жидкостью и три старинных золотых монеты. Раньше никто из нас таких не видел. Мы поделили добычу - мне досталась одна из этих монет, а шкатулку капитан взял себе.";
			link.l1 = "Хм, и что же было дальше?";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Через какое-то время капитану Грегори удалось найти человека, который смог прочитать надпись на крышке той самой шкатулки. Оказалось, что обладатель её содержимого мог связаться со злыми индейскими духами, прочитав заклинание с крышки и смешав свою кровь с жидкостью из пузырька. Наш капитан так и сделал - и превратился в мумию, в живого скелета: в него вселился злой дух! Более того, Грегори получил необъяснимую власть над своей командой, а часть матросов с помощью этой колдовской жидкости обратил в таких же скелетов." + NewStr() + "Странным образом на меня его чары не подействовали - теперь я понимаю, эта старинная монета меня и спасла. Через какое-то время мне удалось бежать, я сменил род занятий - по ходатайству тестя меня взяли штурманом на торговое судно. Беда вот в чём: чем больше людей Грегори и его команда убивают, тем сильнее он становится.";
			link.l1 = "И?..";
			link.l1.go = "4";
		break;

		case "4":
			dialog.text = "Но для каких-то целей ему необходимо собрать все три монеты вместе. Одна досталась Грегори при дележе клада, другая была у нашего боцмана, которого недавно убили в Бас-Тере - ему тогда удалось бежать вместе со мной, и мы изредка встречались. Так что вторая монета наверняка уже у Грегори. И если бы вы не подоспели вовремя, третья тоже оказалась бы в его руках.";
			link.l1 = "Да, интересные вещи вы мне рассказываете!";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Говорю только чистую правду. И если быть до конца откровенным, эта монета жжёт мне карман - ведь они всё равно рано или поздно до меня доберутся!";
			link.l1 = "Почему вы в этом так уверены?";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Ну как же! Капитану Грегори нужны все три золотые монеты Инков! Знаете что, капитан, - может быть, вам удастся победить в этой войне с духами. Меня же наверняка убьют, и тогда все узнают, что такое настоящее зло.";
			link.l1 = "Ну что ж, давай сюда эту монетку, я постараюсь разобраться, что к чему.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DisappearPeopleTakeCoin");
		break;

		case "7":
			dialog.text = "Ага, моя монетка сама пришла ко мне на двух ножках!";
			link.l1 = "В тебе не узнать человека, капитан Грегори! Что с тобой сделали эти злые индейские духи! Ты стал похож на дохлую обезьяну, разрази меня гром!";
			link.l1.go = "8";
		break;

		case "8":
			dialog.text = "Что ты понимаешь, ничтожный человечишка! Сила и власть - вот что важно, а остальное для меня не дороже обглоданной трески. И сейчас я получу от тебя то, чего мне так не хватало.";
			link.l1 = "Получишь, если сможешь как следует держать шпагу своими гнилыми костями!";
			link.l1.go = "9";
		break;

		case "9":
			dialog.text = "Глупый щенок! Сейчас я покажу тебе, чего я достиг за это время! Готовься к смерти!";
			link.l1 = "Ага!";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DisappearPeopleFinalFight");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
