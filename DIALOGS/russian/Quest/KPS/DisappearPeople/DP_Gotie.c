// Узлы 1-3 - первый визит, 4-7 - разбор таблички из храма Инков.

void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "First time":
			NextDiag.TempNode = "First time";
			dialog.text = "Капитан " + GetFullName(PChar) + "? С чем пришли на этот раз?";
			link.l1 = "Пока ни с чем. Всего доброго.";
			link.l1.go = "exit";
		break;

		case "1":
			dialog.text = "Здравствуйте, господин капитан! Чем могу быть полезен?";
			link.l1 = "Здравствуйте, господин Готье. Я " + GetSexPhrase("хотел", "хотела") + " бы узнать, что вы думаете об историях с исчезновением людей? Мне само" + GetSexPhrase("му", "й") + " кое-что известно. Один человек рассказал мне, что некий пиратский капитан Бен Грегори нашёл старинный клад с магическими предметами - шкатулку, внутри которой лежали три старинных золотых монеты и бутылочка с какой-то жидкостью. Этот капитан сумел с чьей-то помощью прочитать надпись на крышке и превратился в мумию, в живого скелета. Что вы скажете об этой истории?";
			link.l1.go = "2";
		break;

		case "2":
			dialog.text = "Страшная история, капитан. Я интересуюсь древней индейской культурой и читал о чём-то подобном в старинных книгах. Этот человек становится сильнее, убивая людей, верно?";
			link.l1 = "Точно так, господин Готье. Штурман с брига ''Удачливый Джокер'' говорил о том же.";
			link.l1.go = "3";
		break;

		case "3":
			dialog.text = "Добро и зло существуют в этом мире бок о бок. Если есть яд, то есть и противоядие. Мы имеем дело со старинным заклятием Инков - видимо, пираты нашли их древний схрон. Вот что я вам скажу, капитан: поищите истину у заброшенного храма, что стоит где-то на Мейне. Быть может, его посещение вам поможет.";
			link.l1 = "Я всё " + GetSexPhrase("понял", "поняла") + ", господин Готье, спасибо за помощь - немедленно отправляюсь туда.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DisappearPeopleToTemple");
		break;

		case "4":
			TakeNItems(PChar, "DisappearPeople_Table", -1);
			dialog.text = "Похоже, это именно то, что нужно, - здесь упоминаются три старинные золотые монеты!";
			link.l1 = "Да, я тоже так думаю. Дело в том, что одна из них у меня. К сожалению, остальные две уже у Бена Грегори.";
			link.l1.go = "5";
		break;

		case "5":
			dialog.text = "Капитану Грегори просто необходима третья монета - без неё он не может покинуть пещеру, где получил свою магическую силу. Только собрав все монеты вместе, он сможет принимать людской облик, не лишаясь колдовских чар. К тому же есть ещё одно важное обстоятельство: убить его может только человек, владеющий одной из трёх золотых монет. Для остальных Грегори бессмертен.";
			link.l1 = "Так что же, выходит, он до сих пор в пещере Барбадоса?";
			link.l1.go = "6";
		break;

		case "6":
			dialog.text = "Выходит так, господин капитан. Ведь выйдя оттуда, он не смог бы творить все те злодеяния, свидетелями которых мы являемся. Да и не может же он разгуливать по городам в образе мумии!";
			link.l1 = "Немедленно отправляюсь на Барбадос - владея одной из этих монет, я могу его убить.";
			link.l1.go = "7";
		break;

		case "7":
			dialog.text = "Да, это так. Но сделать это будет весьма непросто - он набрал уже очень много силы.";
			link.l1 = "Прощайте, господин Готье, и пожелайте мне удачи.";
			link.l1.go = "exit";
			AddDialogExitQuestFunction("DisappearPeopleToBarbados");
		break;

		case "Exit":
			NextDiag.CurrentNode = NextDiag.TempNode;
			DialogExit();
		break;
	}
}
