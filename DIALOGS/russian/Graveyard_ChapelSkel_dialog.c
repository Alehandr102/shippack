// Диалог пасхалочного говорящего скелета в часовне кладбища (квест "Упокоение умерших")
// Скелет рассказывает одну из десяти версий, почему тут поднимаются неупокоенные мертвецы.
void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog,"Links");

	makeref(NPChar,CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch(Dialog.CurrentNode)
	{
		case "exit":
			DialogExit();
		break;

		case "First time":
			// отметим, что ГГ видел/говорил со скелетом - тогда об этом можно спросить смотрителя
			if (CheckAttribute(pchar, "GenQuest.GraveyardQuest")) pchar.GenQuest.GraveyardQuest.ChapelSkelMet = true;
			dialog.text = "Не спеши хвататься за клинок, "+ GetSexPhrase("капитан","капитан") +". Я не из тех, что бродят по ночам и скалят зубы на живых. Просто сижу тут, в старой часовне, и думаю... Раз уж ты упокоил" + GetSexPhrase("", "а") + " остальных - может, выслушаешь и меня?";
			link.l1 = "Откуда вообще здесь берётся вся эта нежить?";
			link.l1.go = "Story";
			link.l2 = "Мне некогда болтать с костями. Прощай.";
			link.l2.go = "exit";
		break;

		case "Story":
			switch (rand(9))
			{
				case 0:
					dialog.text = "Земля здесь дурная, "+ GetSexPhrase("приятель","красавица") +". Сказывают, часовню поставили на старом капище - ещё до того, как сюда пришли белые люди. Кровь, что лили тут идолам, въелась в самую почву. Вот мёртвые и не находят покоя - земля их выталкивает обратно.";
				break;
				case 1:
					dialog.text = "Был тут один... учёный человек, в чёрном балахоне. Копался в склепах по ночам, шептал над костями на латыни. Однажды пропал, а мертвецы с тех пор и поднимаются. Я думаю, он не умер - он где-то рядом, и дёргает нас за ниточки, как кукол.";
				break;
				case 2:
					dialog.text = "Всё дело в обряде. Старого священника, что знал, как правильно класть мёртвых в землю, давно нет. А новые хоронят кое-как, без должных слов. Душа, которую проводили неправильно, не может уйти - вот и возвращается в брошенное тело.";
				break;
				case 3:
					dialog.text = "Чума, "+ GetSexPhrase("друг","милая") +". Лет сто назад тут выкосило полгорода. Хоронили в общих ямах, наспех, не отпевая - просто сваливали и засыпали известью. Столько обиженных мертвецов в одном месте... они помнят, что с ними обошлись как с мусором. И злятся.";
				break;
				case 4:
					dialog.text = "Под криптой есть то, чего знать тебе не надо. Старая печать, и под ней - не то спит, не то ждёт. Пока печать цела, оно лишь тянет к себе мёртвых, поднимает их себе на службу. А если кто её сломает... лучше не доводить до этого.";
				break;
				case 5:
					dialog.text = "Спроси-ка лучше у смотрителя, отчего он так держится за это кладбище и носу с него не кажет. Он знает больше, чем говорит. Я вот думаю, он давным-давно заключил с кем-то сделку - и теперь расплачивается, год за годом, нашими костями.";
				break;
				case 6:
					dialog.text = "Тут лежит проклятое золото, "+ GetSexPhrase("капитан","капитан") +". Пират один зарыл клад прямо в чьей-то могиле, а сверху положил заклятье - чтоб мертвец стерёг добро. Да только проклятье растеклось на всё кладбище. Теперь стерегут все - сами не зная, что.";
				break;
				case 7:
					dialog.text = "Полнолуние, вот что. В иные ночи луна тут висит низко и красная, как ржавое железо. В такие ночи граница между тем светом и этим тончает до волоска. Мёртвые слышат зов и встают - не по злобе, а потому что не понимают, что уже умерли.";
				break;
				case 8:
					dialog.text = "Была тут история про девушку, которую похоронили живой - в горячке приняли за покойницу. Она проснулась под землёй и кричала, пока не задохнулась. С тех пор её злоба будит остальных. Говорят, по ночам из-под земли всё ещё слышен царапающий звук.";
				break;
				case 9:
					dialog.text = "А может, и нет никакой великой тайны. Может, мы просто не хотим уходить. Тут тихо, тут привычно. Кому охота в неведомую тьму, когда можно остаться там, где прожил жизнь? Вы, живые, цепляетесь за жизнь. А мы, мёртвые, цепляемся за смерть.";
				break;
			}
			// упоминание СТАРШЕГО: пасхалка могла выпасть после его убийства ЛИБО когда он вовсе не поднялся
			if (CheckAttribute(pchar, "GenQuest.GraveyardQuest.AvengerKilled"))
			{
				dialog.text = dialog.text + "\n\nИ вот ещё что... Так это ты упокоил"+ GetSexPhrase("","а") +" СТАРШЕГО? Воина из самого дальнего кургана, того, что поднялся отомстить за наш потревоженный сон? При жизни он владел клинком так, что сам Миктлантекутли - владыка царства мёртвых - приметил его и после смерти призвал в свою стражу... Раз уж ты одолел"+ GetSexPhrase("","а") +" того, кого отметил бог мёртвых, - мне ли тебя бояться? Потому и говорю с тобой откровенно.";
			}
			else
			{
				dialog.text = dialog.text + "\n\nИ вот ещё что... Повезло тебе, что СТАРШИЙ не поднялся - воин из самого дальнего кургана, видно, крепко спит. При жизни он владел клинком так, что сам Миктлантекутли - владыка царства мёртвых - приметил его и после смерти призвал в свою стражу. Разбуди ты его - ещё неизвестно, кто бы из вас остался стоять на ногах.";
			}
			DeleteAttribute(NPChar, "dialog"); // одна история за раз: больше со скелетом не поговорить (до следующей пасхалки)
			link.l1 = RandPhraseSimple("Спасибо за рассказ. Покойся с миром.", "Вот оно как... Бывай, старая кость.");
			link.l1.go = "exit";
		break;
	}
}
