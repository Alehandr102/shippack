// Диалог события "Стычка банды и патруля": благодарность за помощь, награды и истории о битве
void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog,"Links");

	makeref(NPChar,CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch(Dialog.CurrentNode)
	{
		case "exit":
			if (CheckAttribute(NPChar, "bGangLeader")) { DeleteAttribute(NPChar, "bGangLeader"); UnmarkCharacter(NPChar); } // снять знак мини-босса после разговора
			LAi_SetCitizenTypeNoGroup(NPChar); // после разговора расходится по своим делам
			DialogExit();
		break;

		// --- Благодарность патруля (ГГ помог солдатам, офицер выжил) ---
		case "ThankPatrol":
			GangWar_RewardPatrol();
			switch (rand(4))
			{
				case 0: dialog.text = "Капитан! Если бы не ваша подмога, эти разбойники перерезали бы нас всех до единого. Корона не забудет вашей услуги. Примите искреннюю благодарность."; break;
				case 1: dialog.text = "Вы подоспели как нельзя кстати, капитан. Ещё немного - и от моего отряда осталась бы лишь груда тел. Благодарю вас от лица короны."; break;
				case 2: dialog.text = "Храбро дрались, капитан! Не каждый рискнёт встать плечом к плечу с патрулём против банды головорезов. Это не останется без награды."; break;
				case 3: dialog.text = "Без вашего клинка нам бы несдобровать. Я непременно доложу губернатору о вашей доблести. Примите мою благодарность, капитан."; break;
				case 4: dialog.text = "Видит Бог, вы спасли нам жизни. Такие люди, как вы, - опора короны в этих диких краях. Не знаю, как и благодарить."; break;
			}
			link.l1 = RandPhraseSimple("Рад"+ GetSexPhrase("","а") +" был"+ GetSexPhrase("","а") +" помочь, офицер.", "Долг каждого - помогать короне.");
			link.l1.go = "exit";
		break;

		// --- Благодарность бандитов (ГГ помог банде, главарь выжил) ---
		case "ThankBandits":
			GangWar_RewardBandits();
			if (CheckAttribute(pchar, "GangWar.bandWithhold")) // штраф - награды нет
			{
				if (pchar.GangWar.bandWithhold == "betray") // в прошлый раз перебил банду после благодарности
				{
					switch (rand(2))
					{
						case 0: dialog.text = "Стой-ка... Я тебя знаю. Прошлый раз ты принял" + GetSexPhrase("", "а") + " нашу благодарность, а после хладнокровно перерезал оставшихся братков. Слухи быстро бегут. Помощь приму, но доли не жди - ребята тебе не верят."; break;
						case 1: dialog.text = "А, это ты... Наслышаны мы. Принял"+ GetSexPhrase("","а") +" долю в прошлый раз - и вырезал"+ GetSexPhrase("","а") +" тех, кто остался. Скажи спасибо, что вообще говорю с тобой. Денег не жди, "+ GetSexPhrase("иуда","змея подколодная") +"."; break;
						case 2: dialog.text = "Тебя тут уже знают, "+ GetSexPhrase("приятель","подруга") +". Кто раз продал братву после рукопожатия - тому веры нет. За подмогу спасибо, но кошель свой я при себе оставлю."; break;
					}
				}
				else // в прошлом событии помогал патрулю/солдатам
				{
					switch (rand(2))
					{
						case 0: dialog.text = "А, это ты... Слыхали мы, что в прошлый раз ты бок о бок с солдатнёй рубил"+ GetSexPhrase("ся","ась") +". Сегодня помог нам, верно, да только доверия к тебе нет. За подмогу спасибо, а доли не жди."; break;
						case 1: dialog.text = "Помощь приму, но кошель оставлю при себе. Кто намедни лизал сапоги короне, тому у нас веры нет. Не серчай, "+ GetSexPhrase("приятель","подруга") +"."; break;
						case 2: dialog.text = "Видели тебя с патрулём в прошлый раз, "+ GetSexPhrase("приятель","подруга") +". Сегодня ты с нами - и на том спасибо, но делиться добром с тем, кто вчера был против нас, мы не станем."; break;
					}
				}
				link.l1 = RandPhraseSimple("Как знаешь.", "Дело твоё. Бывай.");
			}
			else
			{
				switch (rand(4))
				{
					case 0: dialog.text = "Хех, а ты лихо машешь железякой! Без тебя нас бы тут и положили. Мы с попутчиков кое-что натрясли - держи свою долю за помощь. Бывай, и не попадайся солдатне на глаза."; break;
					case 1: dialog.text = "Ну ты и зверь в бою, "+ GetSexPhrase("приятель","подруга") +"! Эти солдатики думали нас как курей перерезать, да не вышло. Вот, бери долю с общего котла - заслужил"+ GetSexPhrase("","а") +"."; break;
					case 2: dialog.text = "А ты "+ GetSexPhrase("свой в доску","своя в доску") +"! Не бросил"+ GetSexPhrase("","а") +" нас в беде. Держи монету - мы добром делимся с теми, кто за нас стоит."; break;
					case 3: dialog.text = "Хорошая рубка вышла, и ты в ней не сплоховал"+ GetSexPhrase("","а") +"! Вот тебе за труды - всё честно натрясли с проезжих. Свидимся ещё на узкой дорожке."; break;
					case 4: dialog.text = "Ловко ты их, ловко! За такую подмогу грех не отблагодарить. Держи звонкую долю, "+ GetSexPhrase("капитан","красотка") +", и помни - банда своих не забывает."; break;
				}
				link.l1 = RandPhraseSimple("Не за что. Удачи на дорогах.", "Деньги лишними не бывают. Бывай.");
			}
			link.l1.go = "exit";
		break;

		// --- История о битве (ГГ не вмешивался, можно расспросить победителя) ---
		case "Story":
			switch (rand(4))
			{
				case 0:
					dialog.text = "Жаркая была сеча, "+ GetSexPhrase("приятель","красавица") +"... Сталь звенела так, что птицы с деревьев сыпались. Многих недосчитались, но и от тех мало кто ушёл живым.";
				break;
				case 1:
					dialog.text = "Видел бы ты, как мы сошлись! Мушкеты гремели, кровь хлестала, крики стояли на всю чащу. Едва выстояли, чего уж там.";
				break;
				case 2:
					dialog.text = "Они выскочили из-за деревьев, мы - в ножи. Рубились до последнего, земля под ногами стала бурой от крови. Но мы их перемололи.";
				break;
				case 3:
					dialog.text = "Такой резни в этих краях давно не видали. Кто-то всех порохом угостить хотел, да не вышло. Остались те, кто покрепче да поудачливей.";
				break;
				case 4:
					dialog.text = "Сошлись лоб в лоб - и ни шагу назад. Кого пуля нашла, кого клинок. Тихо теперь на поляне... только вороньё кружит.";
				break;
			}
			link.l1 = "Да, жаркое было дело. Бывай.";
			link.l1.go = "exit";
		break;

		// --- Повторный разговор после награды ---
		case "AfterThanks":
			dialog.text = "Ещё раз благодарю, "+ GetSexPhrase("капитан","капитан") +". Ступай с миром.";
			link.l1 = "И тебе не хворать.";
			link.l1.go = "exit";
		break;
	}
}
