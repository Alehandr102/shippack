// Подмена груза - развилка губернаторского фрахта. Делец в порту-отправителе ("First time")
// предлагает подменить казённый груз; таможенник при сдаче ("Inspector_Check") сверяет груз,
// затем БЕЗ повторного клика слово передаётся губернатору (GovSwap_AfterInspector -> Common_Mayor.c
// узел GovFreight_SwapResult). Логика - scripts/GovSwap.c. Роллы запекаются при взятии (quests_reaction.c).
void ProcessDialogEvent()
{
	ref NPChar;
	aref Link, NextDiag;

	DeleteAttribute(&Dialog, "Links");

	makeref(NPChar, CharacterRef);
	makearef(Link, Dialog.Links);
	makearef(NextDiag, NPChar.Dialog);

	switch (Dialog.CurrentNode)
	{
		case "exit":
			DialogExit();
			NextDiag.CurrentNode = NextDiag.TempNode;
		break;

		//============ ДЕЛЕЦ-ПОДМЕНЩИК (порт-отправитель) ============
		case "First time":
			dialog.text = RandPhraseSimple(
				"(вполголоса, нагоняя вас) Капитан, на пару слов. Везёте казённый заказ для его превосходительства? Золотая жила, а вы и не знаете. Сделаем так: настоящий товар - мне, а в резиденцию сдадите дешёвку под той же накладной. Клерк губернатора носом водить не станет.",
				RandPhraseSimple(
					"(пристраивается рядом, тихо) Не оборачивайтесь, капитан, просто слушайте. В трюме у вас казённый груз - я знаю. Уступите его мне, а губернатору свезёте что подешевле под той же пломбой. Бумаги сойдутся, никто и не глянет.",
					"(сплёвывает, понижает голос) Капитан, тут выгодное дельце. Заказ его превосходительства - чистое золото. Настоящий товар - мне, а в резиденцию дешёвую подмену. Старый клерк давно не разбирает, что под казённой печатью."
				)
			) + " За хлопоты плачу " + FindRussianMoneyString(GovSwap_Bonus()) + " прямо сейчас. По рукам?";
			link.l1 = "По рукам. Забирай товар. (" + FindRussianMoneyString(GovSwap_Bonus()) + ")";
			link.l1.go = "GovSwap_Accept";
			link.l2 = "Нет. Казённый груз доставлю как есть.";
			link.l2.go = "GovSwap_Decline";
			NextDiag.TempNode = "First time";
		break;

		case "GovSwap_Accept":
			GovSwap_DoSwap();                                  // деньги + флаг подмены + запись журнала
			AddDialogExitQuestFunction("GovSwap_DealerLeave"); // делец уходит на выходе из диалога
			dialog.text = RandPhraseSimple(
				"Вот это разговор! Мои люди заберут товар нынче же ночью, а вам - неприметный груз подешевле под казённой пломбой. Сдавайте смело: коли таможня носа не сунет, никто и не дознается. Попутного ветра, капитан.",
				"Мудрое решение, капитан. К утру вместо вашего товара будет лежать подмена - не отличить, покуда не вскроют. А вскрывать станут вряд ли. Ну, держите уговорённое и ступайте."
			);
			link.l1 = "Бывай.";
			link.l1.go = "exit";
		break;

		case "GovSwap_Decline":
			AddDialogExitQuestFunction("GovSwap_DealerLeave");
			dialog.text = RandPhraseSimple(
				"Честность нынче в цене... жаль. Ну, дело ваше, капитан. Был бы навар, да воля ваша.",
				"Как знаете. Только потом не кусайте локти, капитан, - такие заказы дважды не подворачиваются. Доброго пути."
			);
			link.l1 = "Прощай.";
			link.l1.go = "exit";
		break;

		//============ ТАМОЖЕННИК (досмотр при сдаче) ============
		// после диалога слово передаётся губернатору (GovSwap_AfterInspector), повторно кликать мэра не нужно
		case "Inspector_Check":
			AddDialogExitQuestFunction("GovSwap_AfterInspector");
			if (CheckAttribute(pchar, "CargoQuest.GovSwapCaught"))
			{
				pchar.CargoQuest.GovSwapInspected = "caught";
				dialog.text = RandPhraseSimple(
					"(придирчиво осматривает груз, сверяет клейма и вес с накладной, и хмурится) ...А вот это, капитан, не то, что значится в накладной его превосходительства. Подмена.",
					"(обходит груз, постукивает, сверяется с описью и качает головой) Клейма не те, вес не сходится. Это не казённый товар, капитан. Подмена, и явная."
				) + " Извольте объясниться - и не со мной, а с губернатором.";
				link.l1 = "(промолчать)";
				link.l1.go = "exit";
			}
			else
			{
				pchar.CargoQuest.GovSwapInspected = "passed";
				dialog.text = RandPhraseSimple(
					"(бегло осматривает груз, сверяется с бумагой) Хм... всё чисто, груз соответствует. Ступайте к его превосходительству за расчётом, капитан.",
					"(проходит вдоль груза, сверяет пару клейм, кивает) Всё по описи, капитан. Получайте расчёт у его превосходительства."
				);
				link.l1 = "Благодарю за службу.";
				link.l1.go = "exit";
			}
		break;
	}
}
